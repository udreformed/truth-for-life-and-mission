def close_clause(text: str):
    text = text.rstrip(" ,")
    endings = [
        ("하시며", "하십니다"), ("하시고", "하십니다"),
        ("드리며", "드립니다"), ("받으며", "받습니다"),
        ("이어지며", "이어집니다"), ("나타나며", "나타납니다"),
        ("일어나며", "일어납니다"), ("나아가며", "나아갑니다"),
        ("보이며", "보입니다"), ("되며", "됩니다"), ("되고", "됩니다"),
        ("이며", "입니다"), ("이고", "입니다"),
        ("하며", "합니다"), ("하고", "합니다"),
    ]
    for old, new in endings:
        if text.endswith(old):
            return text[:-len(old)] + new
    return None


def refocus(text: str) -> str:
    sentences = re.findall(r".*?[.!?](?:\s|$)", text.strip())
    if len(sentences) != 2:
        return text
    out = []
    for sentence in sentences:
        sentence = sentence.strip()
        # Remove only a final interpretive/application clause; retain the concrete
        # event or argument before it. Fully interpretive sentences remain flagged
        # for deliberate manual rewriting rather than being damaged mechanically.
        clauses = [c.strip() for c in sentence[:-1].split(",")]
        if len(clauses) >= 2 and INTERPRETIVE.search(clauses[-1]):
            candidate = close_clause(", ".join(clauses[:-1]))
            if candidate and len(candidate) >= 38:
                sentence = candidate
        out.append(sentence)
    return " ".join(out)


def main(source_glob: str, out_dir: str):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    changed = 0
    flagged = []
    for source in sorted(glob.glob(source_glob)):
        data = json.loads(Path(source).read_text(encoding="utf-8"))
        for item in data:
            for field in ("first", "second"):
                # Only apply changes that were reviewed as complete Korean sentences.
                # Mechanical shortening is intentionally not used for final data.
                revised = MANUAL.get((item["month"], item["day"], field), item[field])
                changed += revised != item[field]
                item[field] = revised
                for n, sentence in enumerate(re.split(r"(?<=[.!?])\s+", revised), 1):
                    if INTERPRETIVE.search(sentence):
                        flagged.append((item["month"], item["day"], field, n, sentence))
        target = out / Path(source).name.replace("korean-detailed", "korean-preview")
        target.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"changed_sentences": changed, "manual_review_flags": len(flagged)}, ensure_ascii=False))
    for row in flagged:
        print("\t".join(map(str, row)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
