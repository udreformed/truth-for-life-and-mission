def main(source_glob: str, out_dir: str):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    changed = 0
    counts = {}
    for source in sorted(glob.glob(source_glob)):
        data = json.loads(Path(source).read_text(encoding="utf-8"))
        for item in data:
            for field in ("first", "second"):
                key = (item["month"], item["day"], field)
                if key in OVERRIDES:
                    item[field] = OVERRIDES[key]
                    changed += 1
                count = len(re.findall(r"[.!?](?:\s|$)", item[field]))
                if count not in (2, 3):
                    raise ValueError(f"{key}: {count} sentences")
                counts[count] = counts.get(count, 0) + 1
        target = out / Path(source).name.replace("korean-six-pass", "korean-publication")
        target.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"changed": changed, "sentence_counts": counts}, ensure_ascii=False))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
