TH_REGEX_REPLACEMENTS = [
    (r"MONERGISM BOOKS[\s\S]*$", ""),
    (r"บทที่\s*[IVX\d]+\s*[-–]?\s*", ""),
    (r"\s+([,.;:!?])", r"\1"),
    (r"\n{3,}", "\n\n"),
]


def refine_text(text: str, replacements: list[tuple[str, str]], regexes: list[tuple[str, str]]) -> str:
    for old, new in replacements:
        text = text.replace(old, new)
    for pattern, repl in regexes:
        text = re.sub(pattern, repl, text)
    return text.strip()


def refine(lang: str) -> None:
    path = TMP / f"gods-way-of-peace-{lang}.json"
    backup = TMP / f"gods-way-of-peace-{lang}.pre-revision-backup.json"
    if not backup.exists():
        shutil.copy2(path, backup)
    data = json.loads(path.read_text())

    title_fixes = KO_TITLE_FIXES if lang == "ko" else TH_TITLE_FIXES
    replacements = KO_REPLACEMENTS if lang == "ko" else TH_REPLACEMENTS
    regexes = KO_REGEX_REPLACEMENTS if lang == "ko" else TH_REGEX_REPLACEMENTS

    for chapter in data:
        chapter["title"] = title_fixes.get(chapter["title"], chapter["title"])
        chapter["body"] = refine_text(chapter["body"], replacements, regexes)

    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def main() -> None:
    refine("ko")
    refine("th")
    print("refined gods-way-of-peace ko/th translations")


if __name__ == "__main__":
    main()
