거룩함은 기쁨의 반대가 아닙니다. 죄는 자유와 즐거움을 약속하지만 결국 사람을 묶고 파괴합니다. 하나님께 순종할 때 우리는 창조된 목적에 맞는 자유와 기쁨을 배웁니다.

성화가 더디다고 느껴질 때 낙심할 수 있습니다. 그러나 성화의 완성은 우리의 능력에 달려 있지 않습니다. 구원을 시작하신 하나님께서 그 일을 끝까지 이루십니다.

성도는 이 땅에서 완전해지지 않지만, 그리스도께서 다시 오실 때 영화롭게 되어 죄의 존재와 영향에서 완전히 해방될 것입니다. 그날에는 하나님을 방해 없이 사랑하고 기뻐하며 섬기게 됩니다.

