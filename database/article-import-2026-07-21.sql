3. 생각과 욕망을 말씀으로 살피십시오

죄는 행동 전에 생각과 욕망에서 자랍니다. 마음속의 합리화와 거짓말을 발견하고 성경의 진리로 반박하십시오. “이 정도는 괜찮다”, “나는 피해자이니 그럴 수 있다”, “아무도 모른다”는 생각을 그대로 두지 마십시오.

4. 성령을 의지하여 기도하십시오

자신의 결심만 믿지 말고 유혹을 느끼는 즉시 하나님께 도움을 구하십시오. 성령께서 죄를 깨닫게 하실 때 미루지 말고 반응하십시오. 기도는 죄와 싸우기 위한 준비만이 아니라 실제 싸움의 한 부분입니다.

