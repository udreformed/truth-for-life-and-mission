선교사는 우리와 다른 종류의 신자일까요?

교회는 때때로 선교사를 특별한 영적 사람으로 바라봅니다. 큰 희생을 감당했으니 믿음도 더 강할 것이라 생각하고, 쉽게 지치거나 흔들려서는 안 된다고 기대하기도 합니다.

그러나 선교사도 한 사람의 성도입니다. 그도 죄와 연약함을 가지고 있으며, 날마다 복음의 은혜가 필요합니다. 말씀을 배우고, 기도하며, 자신의 죄를 회개하고, 그리스도를 의지해 살아가야 합니다.

선교사의 특별함은 더 높은 신앙에 있지 않습니다. 그가 맡은 사역의 자리에 있습니다.

모든 성도는 자신을 부인하고 그리스도를 따라야 합니다. 가정과 직장에서 정직하고 거룩하게 살아야 하며, 이웃을 사랑하고 복음을 전해야 합니다. 시간과 재능과 소유도 하나님의 뜻에 따라 사용해야 합니다.

선교사는 이 동일한 제자의 삶을 언어와 문화의 경계를 넘어 감당하도록 교회가 파송한 성도입니다.

그러므로 성도는 선교사를 바라보며 “저 사람은 특별하니 저렇게 살아야 한다”고만 생각해서는 안 됩니다. 오히려 자신도 하나님께서 부르신 자리에서 같은 충성과 헌신으로 살아야 합니다.

선교사는 사역의 결과로 자신의 가치를 증명하려 해서는 안 됩니다. 사람이 많이 모였다고 자신을 높이고, 열매가 더디다고 자신의 존재까지 실패로 판단해서도 안 됩니다.

그의 정체성은 사역의 성패가 아니라 그리스도 안에 있습니다. 그는 자신의 능력 때문에 선택된 사람이 아니라 은혜로 구원받고, 은혜로 부름받은 사람입니다.

이 진리는 모든 성도에게도 같습니다. 성도는 직업의 성공이나 사람들의 인정, 교회에서 맡은 역할로 자신의 가치를 세우지 않습니다. 이미 그리스도 안에서 받아들여졌기 때문에 감사와 순종으로 살아갑니다.

선교사의 삶은 그가 전하는 복음과 분리될 수 없습니다. 복음을 전하면서 가정에서는 사랑 없이 살고, 은혜를 가르치면서 사람을 이용하며, 정직을 말하면서 사역을 과장한다면 그의 증언은 약해집니다. 선교사는 배우자와 자녀를 돌보고, 돈과 관계에서 정직하며, 실패했을 때 변명하지 않고 회개해야 합니다.

그러나 이런 삶 역시 선교사에게만 요구되는 것이 아닙니다. 모든 성도가 가장 가까운 사람에게 먼저 복음으로 살아야 합니다.

교회도 선교사를 잘못 바라보지 않도록 조심해야 합니다.

선교사를 실패해서는 안 되는 영웅이나 계속 성과를 보여 주어야 하는 전문 사역자로 여겨서는 안 됩니다. 지나치게 높이는 것도 옳지 않고, 후원받는 일꾼으로만 대하는 것도 옳지 않습니다.

선교사는 교회의 파송을 받은 한 지체입니다. 기도와 격려가 필요하고, 때로는 쉼과 상담과 목회적 돌봄이 필요합니다. 교회는 선교사의 결과만 묻지 말고 그의 영혼과 가정도 살펴야 합니다.

교회가 선교사의 사역을 살필 때 가장 먼저 물어야 할 것은 규모가 아니라 충성입니다. 복음을 바르게 전하고 있는지, 말씀에 자신을 복종시키는지, 사람을 사랑으로 돌보는지, 정직하게 사역하고 있는지를 살펴야 합니다.

선교사는 특별한 종류의 성도가 아닙니다. 모든 성도에게 맡겨진 믿음과 순종의 삶을 타문화권에서 감당하도록 파송받은 성도입니다.

(3) 교회는 선교에 어떻게 참여하는가

파송하고 동행하며 함께 책임지는 공동체

한 사람을 선교지로 보낸 뒤, 교회는 무엇을 해야 할까요?

선교는 선교사 개인의 사업이 아닙니다. 하나님께서는 교회에 복음을 맡기셨고, 교회는 복음과 교리와 삶으로 사람을 준비시켜 언어와 문화의 경계를 넘어 복음을 전하도록 파송합니다.

그러므로 선교사는 개인적인 열정만으로 떠나서는 안 됩니다. 지역교회는 그의 부르심과 신앙, 인격과 가정, 말씀을 가르치는 능력과 협력하는 태도를 신중하게 살펴야 합니다.

열정만으로는 충분하지 않습니다. 낯선 언어와 문화, 외로움과 갈등, 오랜 기다림과 더딘 열매를 감당하려면 복음과 교리에 대한 분명한 이해가 필요합니다. 지역교회 안에서 먼저 충성하고, 사람을 섬기며, 권면을 받을 줄 아는 사람이어야 합니다.

교회는 선교사를 보낸 뒤 잊어서도 안 됩니다. 재정을 보내고 사역 보고를 받는 것만으로는 충분하지 않습니다. 선교사의 영적 상태와 건강, 부부 관계와 자녀, 쉼과 재충전까지 함께 살펴야 합니다.

선교사가 지치거나 갈등을 겪을 때 무조건 더 견디라고 요구해서도 안 됩니다. 때로는 쉬게 하고, 치료받게 하며, 사역을 조정하거나 귀국하도록 돕는 것이 필요합니다.

교회는 선교사의 성과보다 복음에 대한 충실성을 살펴야 합니다.

몇 명이 모였는지, 건물을 얼마나 세웠는지, 세례를 몇 명에게 베풀었는지는 중요한 정보입니다. 그러나 숫자가 많다고 건강한 선교라고 단정할 수는 없습니다.

사람들이 복음을 바르게 이해하고 있는지, 성경을 배우고 있는지, 현지 지도자가 말씀과 인격 안에서 자라고 있는지, 교회가 선교사 개인에게만 의존하지 않고 서 가는지를 함께 살펴야 합니다.

선교 예산도 같은 기준으로 사용해야 합니다. 눈에 잘 보이는 건물과 행사뿐 아니라 복음 전도, 성경 번역, 교리교육, 현지 지도자 양육, 신학교육, 문서와 미디어 사역에도 관심을 기울여야 합니다.

또한 선교는 몇몇 선교위원만의 일이 되어서는 안 됩니다. 공예배에서 선교를 위해 기도하고, 말씀과 교육을 통해 선교의 의미를 가르치며, 어린이와 청소년에게도 세계선교를 소개해야 합니다. 한 선교사나 한 지역과 오래 관계를 맺고, 교회 전체가 소식을 나누며 함께 기도할 수 있습니다.

선교단체는 중요한 동역자입니다. 그러나 선교사를 보내고 돌보는 교회의 책임을 대신할 수는 없습니다. 교회와 선교단체가 각자의 역할을 분명히 하며 협력해야 합니다.

선교사는 현장에서 섬기고, 교회는 기도와 재정과 목회적 돌봄으로 함께 책임집니다. 이 동역이 있을 때 선교는 한 사람의 외로운 사역이 아니라 교회의 공동 순종이 됩니다.

선교하는 교회는 선교사를 멀리 보내고 소식을 기다리는 교회가 아닙니다. 진리 위에 교회가 세워질 때까지 함께 기도하고 돌보며 책임지는 교회입니다.

(4) 성도는 전도와 선교에 어떻게 참여하는가

자신의 자리에서 시작하는 복음의 사명

해외로 떠나지 않는 성도는 선교에 어떻게 참여할 수 있을까요?

모든 성도가 선교사가 되는 것은 아닙니다. 그러나 복음을 받은 성도라면 누구도 교회에 맡겨진 선교의 사명과 무관하게 살아갈 수 없습니다.

그 참여는 먼저 자신의 삶의 자리에서 시작됩니다.

성도는 가정과 직장에서 정직하고 거룩하게 살아야 합니다. 사랑과 섬김으로 복음을 드러내야 합니다. 그러나 좋은 삶만으로 복음이 충분히 설명되는 것은 아닙니다. 복음은 말로 전해져야 합니다.

가족과 친구와 이웃에게 예수 그리스도의 십자가와 부활, 죄와 회개, 믿음과 구원을 설명해야 합니다. 사람을 교회에 초대하는 일은 중요하지만, 초대만으로 전도의 책임을 다했다고 생각해서는 안 됩니다.

성도는 다음과 같은 방식으로 선교에 참여할 수 있습니다.

1. 가까운 사람에게 복음을 전합니다.

일상의 관계 속에서 그리스도를 말하고, 질문을 들으며, 인내를 가지고 복음을 나눕니다.

2. 구체적으로 기도합니다.

특정 선교사와 국가와 종족을 정하여 지속적으로 기도합니다. 현지 교회와 지도자, 성경 번역과 복음 전도를 위해 기도할 수 있습니다.

3. 정기적으로 후원합니다.

일회성 감동보다 꾸준한 동역을 선택합니다. 눈에 보이는 사업뿐 아니라 복음 전도와 제자훈련, 지도자 양육과 교회 개척도 지원해야 합니다.

4. 선교사와 관계를 맺습니다.

사역 결과만 묻지 말고 선교사와 가족의 삶에도 관심을 가집니다. 선교편지를 읽고 구체적으로 기도하며, 필요한 때 실제적인 도움을 나눕니다.

5. 직업과 은사를 사용합니다.

의료, 교육, 번역, 미디어, 기술, 상담, 행정과 같은 전문성도 복음과 교회를 섬기는 데 사용될 수 있습니다.

6. 보내심의 가능성을 열어 둡니다.

하나님께서 부르시면 교회의 훈련과 검증을 받아 직접 떠날 준비를 합니다.

이 모든 참여는 개인적인 선행으로 끝나서는 안 됩니다. 성도는 교회의 지체로서 함께 기도하고, 함께 보내며, 함께 책임져야 합니다.

선교에 참여한다는 것은 반드시 큰일을 해야 한다는 뜻이 아닙니다. 한 선교사의 소식을 꾸준히 읽는 일, 한 종족을 정하여 기도하는 일, 한 이웃에게 복음을 설명하는 일도 선교적 순종이 될 수 있습니다.

중요한 것은 자신의 자리에서 시작하는 것입니다.

모든 성도가 해외로 가는 것은 아닙니다. 그러나 모든 성도는 자신이 있는 자리에서 복음을 전하고, 기도하고, 보내며, 하나님께서 부르실 때 순종할 준비를 해야 합니다.

(5) 가까운 민족에서 모든 민족까지

이주민 선교와 주님의 다시 오심을 기다리는 교회

우리가 먼 나라로 가지 못하는 동안, 하나님께서 그 나라의 사람을 우리 곁으로 보내실 수도 있습니다.

오늘날 많은 외국인 노동자와 유학생, 결혼이주민과 다문화 가정이 우리 주변에 살아갑니다. 그들 가운데는 자기 나라에서는 복음을 접하기 어려웠던 사람도 있습니다.

교회는 이들을 낯선 외국인이나 도움을 받아야 할 대상으로만 보지 말아야 합니다. 하나님께서 가까이 보내신 이웃으로 받아들여야 합니다.

이주민 선교는 거창한 행사보다 관계에서 시작됩니다. 먼저 인사하고 이름을 묻는 일, 식사를 함께하는 일, 언어와 병원과 행정 절차를 돕는 일, 자녀의 학교생활을 살피는 일에서 관계가 시작될 수 있습니다.

그러나 친절만으로 선교가 완성되지는 않습니다. 그들의 문화를 존중하면서도 복음을 분명하게 전해야 합니다. 조급하게 결단을 강요하지 말고, 성경을 함께 읽고 질문을 들으며, 그리스도를 믿고 교회 안에서 자라도록 도와야 합니다.

이주민은 선교의 대상일 뿐 아니라 복음을 자기 민족에게 전할 수 있는 중요한 동역자입니다.

그들은 이미 본국의 가족과 친척, 친구와 지속적으로 연결되어 있습니다. 전화와 인터넷, 방문과 귀국을 통해 국경을 넘어 관계를 이어 갑니다. 그러므로 한 이주민에게 전해진 복음은 그 사람 한 명에게만 머물지 않고, 그의 관계망을 따라 본국의 가족과 공동체로 전해질 수 있습니다.

특히 외부 선교사가 들어가기 어렵거나 복음이 뿌리내리기 힘든 지역에서도, 그 지역의 언어와 문화와 관계를 가진 이주민은 자연스럽게 복음을 나눌 수 있습니다.

교회는 복음을 믿은 이주민을 단지 도움을 받은 사람으로 남겨 두어서는 안 됩니다. 그리스도의 몸 된 교회의 동등한 지체로 받아들이고, 말씀과 교리 안에서 양육하여 자기 가족과 민족에게 복음을 전하는 제자로 세워야 합니다.

그들이 현재 살고 있는 곳에서 본국의 가족과 친구에게 복음을 전하도록 도울 수 있고, 언젠가 돌아가게 된다면 그곳에서도 복음의 증인으로 살아가도록 준비시킬 수 있습니다.

교회는 가까운 이주민을 사랑하는 자리에서 모든 민족을 향한 선교를 배웁니다.

동시에 아직 복음과 건강한 교회에 접근하기 어려운 민족도 바라보아야 합니다.

여호수아 프로젝트의 2026년 7월 기준 자료에 따르면, 세계에는 약 7,162개의 미전도종족이 있으며, 그 인구는 약 36억 명으로 세계 인구의 약 44%에 해당합니다. 여호수아 프로젝트는 복음주의자가 2% 이하이고 기독교인으로 고백하는 인구가 5% 이하인 종족을 미전도종족으로 분류합니다. 이 수치는 개인의 구원 여부를 판단하는 통계가 아니라, 그 종족 안에 복음을 전하고 사람을 양육할 교회가 충분히 세워지지 않은 현실을 보여 주는 선교학적 자료입니다.

