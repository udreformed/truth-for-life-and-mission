พระสิริแด่พระเจ้าเท่านั้น

เพราะแผนงาน การสำเร็จ และการนำความรอดมาใช้ล้วนมาจากพระเจ้า พระสิริทั้งสิ้นจึงต้องเป็นของพระองค์

พระคัมภีร์คือมาตรฐาน พระคุณคือแหล่งกำเนิด พระคริสต์คือรากฐาน ความเชื่อคือหนทางรับ และพระสิริของพระเจ้าคือเป้าหมายของความรอด

บทที่ 2 หลักคำสอนแห่งพระคุณ

หลักคำสอนแห่งพระคุณเน้นว่า ความรอดตั้งแต่ต้นจนจบเป็นพระราชกิจของพระเจ้าผู้ทรงพระคุณและทรงอธิปไตย

1. ความเสื่อมทรามทั่วทั้งชีวิต

ไม่ได้หมายความว่าทุกคนทำความชั่วทุกอย่างเท่าที่จะทำได้ แต่หมายความว่าบาปกระทบความคิด ความรู้สึก ความตั้งใจ และการกระทำทั้งหมด มนุษย์ไม่สามารถรักพระเจ้าและมาหาพระคริสต์ด้วยกำลังฝ่ายวิญญาณของตนเอง

2. การเลือกโดยพระคุณที่ไม่ขึ้นกับคุณความดี

พระเจ้าไม่ได้ทรงเลือกคนเพราะทรงเห็นล่วงหน้าว่าเขาจะทำดีหรือเชื่อเก่งกว่า แต่ทรงเลือกตามพระประสงค์อันเสรีและเปี่ยมด้วยพระคุณ เหตุผลของการเลือกอยู่ในพระเจ้า ไม่ใช่ในมนุษย์

3. การไถ่ที่แน่นอน

กางเขนของพระคริสต์ไม่ได้เพียงเปิดโอกาสให้คนอาจรอด แต่พระเยซูทรงรับบาปของประชากรของพระองค์จริง ทรงชำระราคาแทนพวกเขา และทรงทำให้พวกเขาคืนดีกับพระเจ้าอย่างสมบูรณ์

นี่คือจุดเน้นสำคัญของความเชื่อปฏิรูป: การไถ่ของพระคริสต์มีเป้าหมายชัดเจน สมบูรณ์ และสำเร็จจริง มิใช่การเสียสละที่ขึ้นอยู่กับมนุษย์ว่าจะทำให้สำเร็จหรือไม่

คำดั้งเดิมว่า “การไถ่ที่จำกัด” ไม่ได้หมายความว่าฤทธิ์อำนาจของพระคริสต์มีข้อจำกัด แต่หมายความว่าพระองค์ทรงช่วยประชากรของพระองค์ให้รอดอย่างแน่นอน

4. การทรงเรียกที่เกิดผล

ข่าวประเสริฐประกาศแก่คนมากมาย แต่พระวิญญาณบริสุทธิ์ทรงเปิดใจผู้ที่พระเจ้าทรงเรียก ให้เข้าใจข่าวประเสริฐและมาหาพระคริสต์ พระคุณไม่ได้บังคับเหมือนความรุนแรง แต่เปลี่ยนใจให้คนยินดีเชื่อ

5. การทรงรักษาผู้เชื่อไว้จนถึงที่สุด

ผู้ที่รอดจริงไม่ได้ยืนหยัดด้วยกำลังของตนเอง แต่พระเจ้าทรงรักษาเขาไว้ในความเชื่อ เขาอาจล้ม แต่พระเจ้าไม่ทรงทอดทิ้ง และทรงนำกลับสู่การกลับใจและความเชื่อ

สรุปคือ คนบาปช่วยตนเองไม่ได้ แต่พระเจ้าทรงช่วยผู้ที่พระองค์ตั้งพระทัยจะช่วยให้รอดอย่างแน่นอนในพระคริสต์

บทที่ 3 อ่านพระคัมภีร์ผ่านพันธสัญญา

ความเชื่อปฏิรูปให้ความสำคัญกับเทววิทยาพันธสัญญา พันธสัญญาคือความสัมพันธ์และพระสัญญาที่พระเจ้าผู้ทรงอธิปไตยทรงตั้งขึ้นกับประชากรของพระองค์

พระคัมภีร์ไม่ใช่การรวมเรื่องและคำสอนที่ไม่เกี่ยวข้องกัน แต่ตั้งแต่ปฐมกาลถึงวิวรณ์ เป็นเรื่องเดียวที่พระเจ้าทรงช่วยประชากรของพระองค์ผ่านพันธสัญญา

การทรงสร้างและความรับผิดชอบของมนุษย์

พระเจ้าทรงสร้างมนุษย์ตามพระฉายา เพื่อเชื่อฟังและถวายพระสิริแด่พระองค์ แต่อาดัมละเมิดพระบัญชา และมนุษยชาติจึงตกอยู่ใต้บาปและความตาย

พระสัญญาแห่งพันธสัญญาพระคุณ

หลังการล้มลง พระเจ้าไม่ทรงทอดทิ้งคนบาป แต่ทรงสัญญาว่าจะส่งพระผู้ช่วยให้รอด พระสัญญานี้ชัดเจนขึ้นผ่านพันธสัญญากับอับราฮัม อิสราเอล และดาวิด

พันธสัญญาใหม่สำเร็จในพระคริสต์

เครื่องบูชา พระวิหาร ปุโรหิต และกษัตริย์ในพันธสัญญาเดิมล้วนชี้ไปยังพระเยซูคริสต์ พระองค์ทรงเป็นปุโรหิตแท้ เครื่องบูชาสมบูรณ์ และกษัตริย์นิรันดร์

พันธสัญญาใหม่ถูกตั้งขึ้นด้วยพระโลหิตของพระองค์ และทั้งยิวกับต่างชาติกลายเป็นประชากรของพระเจ้าผ่านความเชื่อ

เทววิทยาพันธสัญญาช่วยให้เห็นความต่อเนื่องของพระคัมภีร์: พระเจ้าองค์เดียว แผนความรอดเดียว พระคุณเดียว และพระคริสต์องค์เดียวเป็นศูนย์กลางของทุกยุค

บทที่ 4 พระอธิปไตยของพระเจ้าและความรับผิดชอบของมนุษย์

พระเจ้าทรงปกครองประวัติศาสตร์ ชาติ ธรรมชาติ ชีวิตมนุษย์ และความรอดตามพระปัญญาและพระประสงค์อันดีของพระองค์

แต่พระอธิปไตยไม่ใช่ความเชื่อเรื่องชะตากรรมที่ทำให้ความรับผิดชอบและความพยายามไร้ความหมาย พระเจ้าทรงใช้การเลือก การกระทำ การอธิษฐาน การประกาศ และการเชื่อฟังของมนุษย์เพื่อทำให้พระประสงค์สำเร็จ

ที่กางเขน มนุษย์ชั่วฆ่าพระเยซูด้วยความตั้งใจของตนและต้องรับผิดชอบ แต่พระเจ้าทรงใช้เหตุการณ์เดียวกันเพื่อทำให้แผนความรอดที่ทรงกำหนดไว้สำเร็จ

เพราะพระเจ้าทรงอธิปไตย เราจึงไม่หยุดอธิษฐานหรือประกาศ แต่ทำอย่างสัตย์ซื่อ เพราะรู้ว่าพระองค์ทรงใช้สิ่งเหล่านี้

ความจริงนี้ให้การปลอบโยนว่า โลกไม่ได้อยู่ใต้ความบังเอิญ ความทุกข์ไม่หลุดจากพระหัตถ์พระเจ้า และความล้มเหลวของเราไม่สามารถทำลายแผนความรอดของพระองค์

บทที่ 5 พระสิริของพระเจ้าและความยินดีแท้ของมนุษย์

หัวใจของความเชื่อปฏิรูปคือพระสิริของพระเจ้า จุดมุ่งหมายสูงสุดของมนุษย์คือถวายพระสิริแด่พระเจ้าและชื่นชมยินดีในพระองค์ตลอดไป

การถวายพระสิริไม่ได้หมายถึงเพิ่มสิ่งที่พระเจ้ายังขาด เพราะพระองค์ทรงสมบูรณ์และเต็มด้วยพระสิริอยู่แล้ว แต่หมายถึงยอมรับ แสดงออก และยกย่องความยิ่งใหญ่ ความบริสุทธิ์ และพระคุณของพระองค์

การถวายพระสิริไม่ใช่เพียงการกระทำภายนอก แต่รวมถึงท่าทีภายใน: ไว้วางใจและพึ่งพระองค์ ยกพระประสงค์ของพระองค์เหนือความต้องการของตน เชื่อฟังด้วยความรักและขอบพระคุณ ยึดความดีของพระองค์ท่ามกลางความกลัวและความกังวล และชื่นชมยินดีในพระคุณที่ได้รับ

พระสิริของพระเจ้าและความสุขแท้ของมนุษย์ไม่แข่งขันกัน เงิน ความสำเร็จ การยอมรับ และความปลอดภัยอาจให้ความสุขชั่วคราว แต่ไม่อาจเติมเต็มจิตใจได้

มนุษย์พบความพอใจแท้เมื่อรู้จัก รัก และชื่นชมยินดีในพระเจ้า เราจึงไม่ควรแสวงหาเพียงพรจากพระองค์ แต่ควรเห็นว่าพระเจ้าเองทรงเป็นสมบัติและความยินดีสูงสุด

เราถวายพระสิริแด่พระเจ้าได้ทั้งในคริสตจักรและชีวิตประจำวัน เช่น รักครอบครัว ทำงานอย่างซื่อสัตย์ ใช้เงินอย่างรับผิดชอบ ดูแลคนอ่อนแอ ควบคุมคำพูดและความปรารถนา วางใจในความดีของพระเจ้าท่ามกลางความทุกข์ และประกาศข่าวประเสริฐ

บทที่ 6 ดำเนินชีวิตตามความเชื่อปฏิรูป

ความเชื่อปฏิรูปไม่สมบูรณ์ด้วยการมีความรู้ด้านหลักคำสอนเท่านั้น หลักคำสอนแท้ต้องเปลี่ยนการนมัสการ บุคลิก และชีวิต

ดำเนินตามพระวจนะ

อ่าน เรียน และนำความคิด วัฒนธรรม และประสบการณ์ของตนมาอยู่ใต้การตัดสินของพระคัมภีร์ อย่าเชื่อฟังเฉพาะข้อที่ชอบ

ถ่อมใจในพระคุณ

ผู้ที่เชื่อว่าความรอดเป็นพระคุณทั้งหมดไม่ควรดูหมิ่นผู้อื่น จงจำว่า หากไม่มีพระคุณ เราก็ไม่อาจมาหาพระเจ้าได้

รักคริสตจักร

ความเชื่อปฏิรูปไม่ใช่ความเชื่อแบบอยู่คนเดียว จงอยู่ในคริสตจักรที่ดี เรียนพระวจนะ รับพิธีศักดิ์สิทธิ์ และเติบโตร่วมกับพี่น้อง

สัตย์ซื่อต่อการทรงเรียก

การรับใช้พระเจ้าไม่ได้จำกัดอยู่ที่งานศิษยาภิบาลหรือพันธกิจ บ้าน งาน และชีวิตประจำวันล้วนเป็นสถานที่แห่งการทรงเรียก

ไว้วางใจพระพรหมคุณในความทุกข์

การเชื่อในพระอธิปไตยไม่ได้ทำให้ความทุกข์เบาลงทันที แต่ช่วยให้ยึดพระปัญญาและความดีของพระเจ้า แม้ยังไม่เข้าใจ

ประกาศข่าวประเสริฐ

การทรงเลือกและพระอธิปไตยไม่ลดความสำคัญของการประกาศ พระเจ้าทรงเรียกประชากรของพระองค์ผ่านการประกาศข่าวประเสริฐ

ระวังความหยิ่งทางหลักคำสอน

อย่าอวดชื่อ “ปฏิรูป” หรือใช้หลักคำสอนเป็นอาวุธเพื่อชนะการโต้เถียง ความเชื่อปฏิรูปแท้ทำให้ยำเกรงพระเจ้า รักพระคริสต์ และรับใช้ผู้อื่นด้วยความถ่อมใจ

คริสตจักรและผู้เชื่อต้องรับการปฏิรูปต่อไปตามพระคัมภีร์ มิใช่เปลี่ยนความจริงตามกระแสยุค แต่แก้ไขตนตามพระวจนะที่ไม่เปลี่ยนแปลง

สาระสำคัญ

ความเชื่อปฏิรูปคือความเชื่อที่กลับสู่พระคัมภีร์

คำประกาศทั้งห้าสรุปมาตรฐาน แหล่งกำเนิด รากฐาน หนทางรับ และเป้าหมายของข่าวประเสริฐ

หลักคำสอนแห่งพระคุณสอนว่า ความรอดตั้งแต่ต้นจนจบเป็นพระคุณอธิปไตยของพระเจ้า

การไถ่ของพระคริสต์ไม่ได้เพียงสร้างความเป็นไปได้ แต่ช่วยประชากรของพระองค์ให้รอดจริงอย่างแน่นอนและสมบูรณ์

