สำหรับผู้เชื่อชาวไทย พื้นที่พันธกิจแห่งแรกอาจเป็นครอบครัว พ่อแม่ ญาติพี่น้อง หรือเพื่อนที่ยังไม่เชื่อพระเยซู

บางครอบครัวอาจเข้าใจว่าการเป็นคริสเตียนคือการทอดทิ้งครอบครัว หรือปฏิเสธความเป็นไทย ผู้เชื่อจึงต้องดำเนินชีวิตด้วยความรัก ความสุภาพ และความอดทน

เราควรเคารพพ่อแม่และผู้ใหญ่ ไม่พูดดูหมิ่นความเชื่อของเขา และไม่สร้างความขัดแย้งโดยไม่จำเป็น แต่การเคารพครอบครัวไม่ได้หมายความว่าเราต้องซ่อนความเชื่อ

เราควรบอกอย่างอ่อนสุภาพว่า เราเชื่อใคร เหตุใดเราจึงเชื่อ และพระเยซูคริสต์ทรงช่วยคนบาปให้รอดอย่างไร

ชีวิตที่ดีเป็นส่วนสำคัญของคำพยาน หากเราพูดเรื่องความรักแต่ไม่รักคนในบ้าน พูดเรื่องความจริงแต่ไม่ซื่อสัตย์ หรือพูดเรื่องการให้อภัยแต่ไม่ยอมให้อภัย คำพยานของเราจะอ่อนกำลังลง

แต่ชีวิตที่ดีอย่างเดียวไม่เพียงพอ ข่าวประเสริฐต้องได้รับการอธิบายด้วยคำพูด คนต้องได้ยินเรื่องพระเจ้า บาป ไม้กางเขน การเป็นขึ้นจากความตาย การกลับใจ และความเชื่อในพระคริสต์

การประกาศกับครอบครัวอาจใช้เวลานาน บางคนอาจปฏิเสธหรือโกรธ เราไม่ควรใช้อารมณ์หรือพยายามเอาชนะการโต้เถียง แต่เราก็ไม่ควรเลิกอธิษฐานและเงียบตลอดไป

จงรักเขา รับฟังคำถาม อธิบายอย่างชัดเจน และวางใจว่าพระวิญญาณบริสุทธิ์ทรงเปิดใจมนุษย์ได้

พันธกิจยังเริ่มต้นในสถานที่ธรรมดา

• บ้าน

• โรงเรียน

• มหาวิทยาลัย

• ที่ทำงาน

• ตลาด

• หมู่บ้าน

• โรงงาน

• ร้านค้า

• กลุ่มเพื่อน

• โลกออนไลน์

เราไม่จำเป็นต้องรอเวทีใหญ่ เราอาจเริ่มจากการอธิษฐานเผื่อคนหนึ่งคน เริ่มสนทนาเรื่องความเชื่อ อ่านพระคัมภีร์ด้วยกัน หรือชวนเขามารู้จักคริสตจักร

การเชิญคนมาคริสตจักรเป็นสิ่งที่ดี แต่เราเองก็ควรเรียนรู้ที่จะอธิบายข่าวประเสริฐอย่างง่ายและถูกต้อง

พันธกิจไม่ได้เริ่มจากการเดินทางไปไกล แต่เริ่มจากการเป็นพยานของพระคริสต์ในที่ที่พระเจ้าทรงวางเราไว้

3. คริสตจักรไทยก็เป็นคริสตจักรที่ส่งคนออกไปได้

คริสตจักรเล็กก็มีส่วนในพันธกิจได้

บางคนคิดว่า คริสตจักรไทยยังเล็ก มีสมาชิกไม่มาก และมีทรัพยากรจำกัด เราจึงควรรอรับความช่วยเหลือต่อไปก่อน แล้วค่อยคิดเรื่องการส่งคนในอนาคต

แต่พันธกิจไม่ใช่งานที่เริ่มเมื่อคริสตจักรมีเงินเหลือ

พระเจ้าไม่ได้เรียกเฉพาะคริสตจักรใหญ่หรือคริสตจักรร่ำรวยให้เชื่อฟังพระมหาบัญชา คริสตจักรทุกแห่งมีส่วนได้ตามกำลังที่พระเจ้าประทาน

คริสตจักรเล็กอาจเริ่มจากสิ่งเหล่านี้

• อธิษฐานเผื่อประเทศหรือกลุ่มชนหนึ่งเป็นประจำ

• สนับสนุนผู้รับใช้ด้วยจำนวนเงินเล็กน้อยแต่ต่อเนื่อง

• ร่วมมือกับคริสตจักรอื่นในการส่งผู้รับใช้

• ฝึกเยาวชนให้รักพระวจนะและการประกาศ

• ส่งสมาชิกไปรับใช้ในพื้นที่อื่นภายในประเทศไทย

• ดูแลครอบครัวของผู้ที่ถูกส่งออกไป

พระเจ้าไม่ได้ทรงเรียกร้องสิ่งที่เราไม่มี แต่ทรงเรียกให้เราใช้สิ่งที่พระองค์ประทานแล้วอย่างซื่อสัตย์

การถวายเพื่อพันธกิจไม่ควรเกิดจากอารมณ์เพียงครั้งเดียว คริสตจักรควรเรียนรู้การถวายอย่างสม่ำเสมอ แม้จำนวนไม่มาก เพราะพันธกิจเป็นความรับผิดชอบร่วมกัน

คริสตจักรไทยควรขอบพระคุณพระเจ้าสำหรับมิชชันนารีและคริสตจักรจากประเทศต่าง ๆ ที่นำข่าวประเสริฐมาถึงประเทศไทย

แต่การได้รับความช่วยเหลือไม่ได้หมายความว่าเราต้องเป็นผู้รับอยู่ตลอดไป ผู้ที่ได้รับพระคุณย่อมถูกเรียกให้ส่งต่อพระคุณนั้นแก่ผู้อื่น

เรื่องเงินก็ต้องเข้าใจอย่างถูกต้อง ผู้ที่ถวายมากกว่าไม่ได้เป็นเจ้าของคริสตจักร และไม่ได้มีสิทธิ์ควบคุมทุกอย่างเพราะเป็นผู้สนับสนุน ขณะเดียวกัน คริสตจักรที่ได้รับความช่วยเหลือก็ไม่ควรมอบความรับผิดชอบทั้งหมดให้ชาวต่างชาติ

ทั้งผู้ให้และผู้รับต้องรับใช้กันในฐานะพี่น้องในพระคริสต์ และอยู่ใต้พระวจนะเดียวกัน

คริสตจักรไทยควรสนใจทั้งพันธกิจภายในประเทศและต่างประเทศ

ภายในประเทศไทยยังมีหมู่บ้าน เขตเมือง ชุมชนชาติพันธุ์ และพื้นที่ชายแดนอีกมากที่ยังไม่มีคริสตจักรที่มั่นคง ส่วนประเทศเพื่อนบ้านและชนชาติอื่นก็ยังต้องการผู้ประกาศข่าวประเสริฐ

เราไม่ควรกล่าวว่า “ประเทศไทยยังมีงานมาก จึงไม่ต้องสนใจต่างประเทศ” และไม่ควรสนใจต่างประเทศจนละเลยคนที่อยู่ใกล้เรา

พระเยซูทรงเรียกคริสตจักรให้มองทั้งเยรูซาเล็ม ยูเดีย สะมาเรีย และที่สุดปลายแผ่นดินโลกพร้อมกัน

คริสตจักรไทยไม่ใช่เพียงคริสตจักรที่รับข่าวประเสริฐ แต่เป็นคริสตจักรที่ได้รับมอบหมายให้ส่งต่อข่าวประเสริฐด้วย

4. ผู้เชื่อทุกคนมีส่วนในพันธกิจได้

อธิษฐาน ประกาศ ถวาย ต้อนรับ และส่งคนออกไป

ไม่ใช่ผู้เชื่อทุกคนจะเดินทางไปต่างประเทศ แต่ผู้เชื่อทุกคนมีส่วนในพันธกิจได้

1. ประกาศแก่คนใกล้ตัว

เริ่มจากครอบครัว เพื่อน เพื่อนร่วมงาน และเพื่อนบ้าน อธิษฐานเผื่อเขา รับฟังคำถาม และอธิบายข่าวประเสริฐด้วยความอดทน

2. อธิษฐานอย่างเจาะจง

เลือกมิชชันนารี ประเทศ เมือง หรือกลุ่มชนหนึ่ง แล้วอธิษฐานอย่างต่อเนื่อง อธิษฐานให้มีการประกาศ ให้มีผู้กลับใจ ให้มีคริสตจักรที่มั่นคง และให้ผู้รับใช้ได้รับกำลังจากพระเจ้า

3. ถวายอย่างสม่ำเสมอ

เราไม่จำเป็นต้องรวยก่อนจึงจะถวายได้ จำนวนเงินอาจไม่มาก แต่ความสัตย์ซื่อและความต่อเนื่องมีความสำคัญ

4. รู้จักและดูแลมิชชันนารี

อย่าถามเฉพาะว่า มีคนมาเชื่อกี่คน หรือสร้างอาคารได้กี่แห่ง มิชชันนารีก็เป็นสมาชิกคนหนึ่งของคริสตจักร มีความเหนื่อย ความโดดเดี่ยว และความอ่อนแอ เราสามารถอ่านจดหมายข่าว อธิษฐาน ส่งข้อความให้กำลังใจ และดูแลครอบครัวของเขา

5. ใช้อาชีพและความสามารถ

ครู พยาบาล ช่าง เกษตรกร พ่อค้า นักแปล ผู้ทำสื่อ และคนทำงานด้านเทคโนโลยี ล้วนใช้ความสามารถของตนเพื่อรับใช้ข่าวประเสริฐได้ อาชีพไม่ใช่เพียงช่องทางหาเงิน แต่อาจเป็นเครื่องมือที่พระเจ้าทรงใช้เปิดประตูให้เรารับใช้ผู้คน

6. ต้อนรับคนจากชนชาติอื่น

เราอาจพบแรงงานจากเมียนมา ลาว หรือกัมพูชาในตลาด โรงงาน โรงเรียน โรงพยาบาล หรือชุมชน เราอาจเริ่มจากการทักทาย ถามชื่อ รับประทานอาหารร่วมกัน หรือช่วยเรื่องภาษาและการดำเนินชีวิต แต่เราไม่ควรหยุดเพียงความช่วยเหลือ จงสร้างความสัมพันธ์ อ่านพระคัมภีร์ร่วมกัน และบอกข่าวประเสริฐอย่างชัดเจน

7. เปิดใจต่อการทรงเรียก

ผู้เชื่อทุกคนควรถามว่า “หากพระเจ้าทรงเรียกข้าพเจ้าให้ไปอีกจังหวัดหนึ่ง อีกกลุ่มภาษา หรืออีกประเทศหนึ่ง ข้าพเจ้าพร้อมจะเชื่อฟังหรือไม่” เราไม่ควรคิดทันทีว่า “งานนี้ไม่ใช่สำหรับฉัน” เพราะพระเจ้าอาจทรงใช้ประสบการณ์ อาชีพ ภาษา หรือความสัมพันธ์ของเราในทางที่เราไม่เคยคาดคิด

หากพระเจ้าทรงเรียกฉันให้เป็นมิชชันนารี

ความปรารถนาที่จะเป็นมิชชันนารีเป็นสิ่งที่ดี แต่ความรู้สึกตื่นเต้นเพียงอย่างเดียวไม่เพียงพอ

ผู้ที่ต้องการเป็นมิชชันนารีไม่ควรตัดสินใจและออกไปตามลำพัง เขาควรได้รับการฝึกฝนและการยืนยันจากคริสตจักรท้องถิ่น

เขาควรเตรียมตัวอย่างน้อยในด้านต่อไปนี้

• เข้าใจข่าวประเสริฐและพระคัมภีร์อย่างชัดเจน

• ซื่อสัตย์ในการรับใช้คริสตจักรของตนเอง

• เติบโตด้านอุปนิสัย การใช้เงิน ความบริสุทธิ์ และการทำงานร่วมกับผู้อื่น

• เรียนรู้ภาษาและวัฒนธรรมของคนที่จะรับใช้

• รับประสบการณ์จากงานจริงภายใต้การดูแลของผู้นำ

• รับการส่งและการดูแลจากคริสตจักร

ผู้ที่ต้องการรับใช้คนไกลควรเรียนรู้ที่จะรับใช้คนใกล้ก่อน ผู้ที่ไม่ยอมรับคำตักเตือนหรือไม่สามารถทำงานร่วมกับผู้อื่น จะพบปัญหาใหญ่ขึ้นเมื่อไปอยู่ในอีกวัฒนธรรมหนึ่ง

งานระยะสั้นอาจช่วยให้เราเห็นความเป็นจริงของพันธกิจ แต่ไม่ได้พิสูจน์ทันทีว่าเราถูกเรียกให้เป็นมิชชันนารีระยะยาว

คริสตจักรควรช่วยตรวจสอบความเชื่อ อุปนิสัย ครอบครัว ความสามารถ และความพร้อมของผู้ที่จะไป เมื่อส่งออกไปแล้วก็ต้องอธิษฐาน ติดต่อ และดูแลเขาอย่างต่อเนื่อง

การทรงเรียกที่แท้จริงไม่ทำให้เราปฏิเสธการฝึกฝน แต่ทำให้เรายอมเตรียมตัวอย่างถ่อมใจภายใต้การดูแลของคริสตจักร

5. ชนชาติต่าง ๆ อยู่ใกล้เราแล้ว

จากประเทศไทยไปสู่ประเทศเพื่อนบ้านและชนทุกชาติ

เมื่อพูดถึงพันธกิจต่างประเทศ เราอาจคิดว่าต้องขึ้นเครื่องบินและเดินทางไกลเสมอ แต่วันนี้ผู้คนจากหลายประเทศได้เข้ามาอยู่ใกล้เราแล้ว

ในประเทศไทยมีแรงงานจากเมียนมา ลาว และกัมพูชา มีนักศึกษา ชาวต่างชาติ ครอบครัวอพยพ ผู้ลี้ภัย คนไร้สัญชาติ และชุมชนชาติพันธุ์หลายภาษา

บางคนทำงานในโรงงาน งานก่อสร้าง งานเกษตร หรือภาคบริการ บางครอบครัวอยู่ในประเทศไทยมาหลายปี แต่ยังไม่มีเพื่อนคริสเตียนและไม่เคยได้ยินข่าวประเสริฐอย่างชัดเจน

คริสตจักรไม่ควรมองคนเหล่านี้เป็นเพียงแรงงานราคาถูก คนแปลกหน้า หรือผู้รับความช่วยเหลือ

เขาเป็นมนุษย์ที่พระเจ้าทรงสร้างตามพระฉายาของพระองค์ และอาจเป็นคนที่พระเจ้าทรงนำมาอยู่ใกล้เราเพื่อให้ได้ยินข่าวประเสริฐ

การต้อนรับอาจเริ่มจากสิ่งเล็กน้อย

• ทักทายเขา

• เรียกชื่อเขา

• รับประทานอาหารร่วมกัน

