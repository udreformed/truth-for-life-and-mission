1장. 성화란 무엇인가

성화란 하나님께서 성령으로 믿는 사람을 새롭게 하셔서 죄의 지배를 점점 약화시키고, 생각과 마음과 행동에서 그리스도를 닮아 가게 하시는 은혜의 역사입니다.

칭의와 성화는 서로 구별되지만 분리되지 않습니다. 칭의에서 하나님은 그리스도의 의를 근거로 죄인을 단번에 의롭다고 선언하십니다. 성화에서는 성령께서 그 사람의 실제 삶을 평생에 걸쳐 변화시키십니다.

칭의는 완전하며 반복되지 않습니다. 성화는 아직 불완전하며 점진적으로 이루어집니다. 우리의 구원 확신은 성화의 성취 정도가 아니라 그리스도의 완전한 의에 근거합니다. 그러나 참으로 의롭다 하심을 받은 사람에게는 반드시 성화의 열매가 나타납니다.

성화는 사람의 의지력만으로 이루어지지 않습니다. 성령께서 우리 안에서 소원을 주시고 행하게 하십니다. 동시에 하나님은 우리에게 죄를 피하고, 말씀을 배우고, 기도하며, 몸과 마음을 의의 도구로 드리라고 명령하십니다.

그러므로 성화는 “하나님이 하시니 나는 아무것도 하지 않는다”는 수동적인 태도도 아니며, “내 힘으로 나를 바꾼다”는 자기구원도 아닙니다. 성령의 능력을 의지하여 적극적으로 순종하는 삶입니다.

2장. 그리스도인은 왜 계속 죄와 싸우는가

거듭난 사람은 새로운 마음과 새로운 삶의 방향을 받았지만, 이 세상에서는 죄의 잔재가 여전히 남아 있습니다. 죄는 더 이상 성도를 지배하는 왕은 아니지만, 계속 유혹하고 속이며 순종을 방해하는 적으로 남아 있습니다.

성경이 하나님께로부터 난 사람이 죄를 짓지 않는다고 말할 때, 그것은 한 번도 죄를 범하지 않는다는 뜻이 아닙니다. 죄를 아무렇지 않게 받아들이고 계속 그 지배 아래 살아가지 않는다는 뜻입니다.

참된 성도도 심각하게 넘어질 수 있고, 같은 죄를 반복할 수도 있습니다. 그러나 성령께서는 그 사람을 죄에 무감각하게 내버려 두지 않으십니다. 죄를 깨닫게 하시고, 회개하게 하시며, 다시 그리스도께 나아가 싸우게 하십니다.

죄와 싸우고 있다는 사실 자체가 구원의 근거는 아니지만, 새 생명이 있다는 중요한 열매입니다. 죄를 슬퍼하고 미워하며 하나님께 순종하기를 원하는 마음은 성령께서 일하고 계신 표지입니다.

성도는 이 땅에서 죄 없는 완전 상태에 이르렀다고 주장할 수 없습니다. 자신의 성숙을 자랑하기보다 날마다 죄를 고백하고 은혜를 의지해야 합니다. 동시에 “나는 원래 이런 사람”이라며 죄를 합리화해서도 안 됩니다.

3장. 죄죽임이란 무엇인가

죄죽임은 성령의 능력으로 우리 안에 남아 있는 죄의 욕망과 습관과 지배력을 약화시키고, 그것에 순종하지 않는 것입니다. 성경이 몸의 행실을 죽이라고 명령할 때, 육체를 학대하거나 몸 자체를 악하게 여기라는 뜻이 아닙니다.

죄와의 싸움의 핵심은 특별한 말로 사탄을 결박하는 데 있지 않습니다. 악한 영의 유혹을 가볍게 여길 수는 없지만, 우리가 매일 싸워야 할 가장 가까운 적은 자기 안의 죄입니다.

죄죽임은 단순히 겉으로 드러난 나쁜 행동을 잠시 멈추는 것이 아닙니다. 행동 뒤에 있는 욕망, 두려움, 교만, 불신, 자기 사랑을 살펴야 합니다. 뿌리를 다루지 않으면 같은 죄가 다른 모습으로 나타납니다.

