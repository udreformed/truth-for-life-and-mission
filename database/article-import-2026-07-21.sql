힌두교와 불교 전통에서는 죽음 이후 윤회하여 다른 생을 산다고 설명합니다. 그러나 인간의 깨달음이나 종교적 체험만으로 그 주장이 참이라는 사실을 확증할 수는 없습니다. 세상은 끝없이 돌고 도는 것일까요? 아니면 역사를 시작하시고 마침내 심판하시는 창조주 하나님이 계신 것일까요?

아무리 위대한 사람이라 해도 죽음 이후의 세계를 인간의 지혜로 발견하여 보장할 수는 없습니다. 죽음 이후의 삶은 우리가 만들어 내거나 조종할 수 있는 영역이 아닙니다. 따라서 누군가가 발견했다는 원리나 신념이 우리의 영원한 운명을 책임질 수는 없습니다.

(2) 이 세상 모든 것을 창조하신 하나님

만일 이 세상과 사람을 만드신 창조주 하나님이 실제로 계신다면, 오직 그 하나님만이 인간에게 죽음의 의미와 죽음 이후의 삶에 관해 참되게 말씀하실 수 있습니다.

많은 사람은 하나님이 계시는지 확증할 방법이 없다고 단정합니다. 여러 종교가 서로 다른 신을 말하기 때문에 신에 관해 정확히 알 수 없다고 생각하기도 합니다. 어떤 사람은 순수한 마음으로 신을 추구하면 결국 신의 은총을 입어 천국에 이를 것이라고 말하고, 다른 사람은 신이 없다고 믿습니다. 그러나 어느 쪽이든 인간의 추측만으로는 확실한 답에 이를 수 없습니다.

그렇다면 하나님과 죽음 이후의 일에 관해 확실한 답을 얻을 방법이 있을까요? 만일 창조주 하나님이 계신다면, 그분이 먼저 자신을 알려 주셔야 합니다. 무한하신 하나님께서 유한한 인간이 이해할 수 있도록 자신을 낮추어 분명한 말씀으로 자신을 계시하셔야 합니다. 성경은 바로 하나님께서 그렇게 자신을 알려 주셨다고 증언합니다.

(3) 하나님께서 특별히 보여 주신 말씀

세상의 시작과 끝, 인간의 죽음과 죽음 이후의 삶을 분명히 말하는 책이 있습니다. 바로 성경입니다. 성경은 영원하신 하나님께서 온 세상을 창조하셨으며, 모든 사람과 역사가 하나님의 손 안에 있다고 선언합니다. 또한 세상에 왜 고통과 악과 불의가 존재하는지, 인간이 무엇으로부터 구원받아야 하며 구원이 무엇인지를 설명합니다.

성경은 오랜 세월 동안 서로 다른 시대와 환경에 살았던 여러 저자를 통해 기록된 예순여섯 권의 책으로 이루어져 있습니다. 그런데도 창조와 타락, 심판과 구원, 그리고 예수 그리스도 안에서 이루어지는 하나님의 구원이라는 하나의 일관된 이야기를 전합니다. 성경의 통일성은 한 분 하나님께서 자신의 구원 역사를 계시하셨다는 사실을 보여 줍니다.

성경은 수천 년 동안 수많은 사람에게 읽혔고, 그 말씀을 통해 많은 사람이 하나님을 알고 믿게 되었습니다. 그러나 성경의 권위는 단지 오래되었거나 많이 읽혔다는 사실에만 있지 않습니다. 성경은 스스로 하나님의 말씀이라고 증언하며, 그 중심인 예수 그리스도 안에서 약속과 성취가 하나로 이어집니다. 성령님께서는 이 말씀을 통해 그 진실성과 권위를 사람의 마음에 확증하십니다.

성경은 단지 여러 종교 가운데 하나의 종교 사상을 소개하는 책이 아닙니다. 성경은 하나님께서 세상 사람들에게 주신 그분의 말씀입니다.

(4) 성경은 무엇을 말하는가

이제 우리는 성경이 하나님과 인간에 관해 무엇을 말하는지 분명히 알고 깊이 생각해야 합니다. 인간의 생각만으로 알아낼 수 없는 하나님과 구원의 진리를 성경이 가르치는 대로 살펴보겠습니다.

① 하나님에 대하여

성경의 첫 책인 창세기는 “태초에 하나님이 천지를 창조하시니라”라고 선언합니다. 성경의 목적은 자연과학 교과서처럼 창조의 모든 과정을 설명하는 데 있지 않습니다. 성경은 하나님에 관한 가장 근본적인 진리를 선포합니다. 하나님은 온 우주와 눈에 보이는 것과 보이지 않는 모든 것을 창조하신 전능하신 창조주이십니다.

하나님은 시작과 끝이 없으신 영원한 영이시며, 거룩하고 선하시며 공의로우십니다. 그분의 지혜와 지식, 사랑과 능력에는 한계가 없습니다.

또한 하나님은 자신의 영광을 다른 자에게 주지 않으시는 분입니다. 하나님께서 죄인을 구원하시고 불의를 심판하시는 모든 일은 그분의 거룩함과 사랑과 공의를 드러냅니다. 하나님은 창조주이시며 모든 것을 선하신 뜻대로 다스리시는 주권자이시므로, 모든 영광과 예배를 받기에 합당하십니다. 이 세상의 그 무엇도 하나님과 비길 수 없습니다.

② 인간에 대하여

성경은 하나님께서 사람을 다른 피조물과 구별하여 특별하게 지으셨다고 말합니다. 사람은 하나님의 형상대로 지음 받아 생각하고 판단하며 선택하고, 하나님을 알고 사랑하며 그분의 뜻에 순종하도록 창조되었습니다. 인간의 의지는 창조주로부터 독립된 무한한 자유가 아니라, 하나님 앞에서 책임 있게 선택하는 피조물의 의지입니다.

그러나 모든 사람은 첫 사람 아담 안에서 처음 창조되었을 때의 온전한 상태를 잃었습니다. 아담은 하나님께서 주신 큰 자유와 특권을 누리면서도, 선악을 알게 하는 나무의 열매를 먹지 말라는 명령을 어겼습니다. 이것은 단순한 실수가 아니라 주님이신 하나님께 대한 반역이었습니다. 하나님께서는 하나님처럼 높아지려 한 아담의 죄를 심판하셨고, 그 결과 죄와 육체적 죽음과 영적 죽음이 인류에게 들어왔습니다.

성경은 모든 사람이 죄인이라고 분명히 말합니다. 죄는 하나님의 계명에 어긋나는 행동만이 아니라, 마음으로 하나님을 주님으로 인정하지 않고 자신이 삶의 주인이 되려는 반역입니다. 아담 이후 모든 사람은 죄로 부패한 본성을 가지고 태어나며, 스스로 하나님을 사랑하거나 구원에 이를 수 없습니다.

③ 심판에 대하여

성경은 아담 이후 모든 사람이 하나님의 명령을 어기며 살아가고, 스스로는 하나님의 선하신 뜻을 바르게 알거나 온전히 행할 수 없다고 말합니다. 사람은 주님이신 하나님을 떠나 자신이 주인이 되어 살아가지만, 그러한 삶은 참된 행복에서 떠나 죄의 종으로 사는 삶입니다.

인간의 타락으로 세상은 죄와 죽음과 고통 아래 놓이게 되었습니다. 모든 질병이나 재난을 특정한 사람의 특정한 죄에 대한 직접적인 형벌이라고 단정할 수는 없습니다. 그러나 세상에 존재하는 고통과 죽음은 온 인류가 하나님을 떠나 타락한 결과이며, 모든 사람이 마침내 하나님의 심판 앞에 서게 된다는 사실을 보여 줍니다.

죽음은 몸의 생명이 끝나는 것만을 뜻하지 않습니다. 성경은 사람이 죽은 뒤 하나님의 심판을 받으며, 그리스도 밖에 있는 자는 하나님과 영원히 분리되는 형벌을 받는다고 가르칩니다.

하나님의 심판은 사람이 정한 기준으로 겉보기에 착한 사람과 나쁜 사람을 나누는 심판이 아닙니다. 하나님은 모든 생각과 동기와 행위를 완전히 아십니다. 하나님께서 사람을 창조하신 목적대로 그분을 사랑하고 모든 영광을 돌리지 않은 죄까지도 공의롭게 심판하십니다.

그러므로 모든 사람은 죄로 인해 하나님의 의로운 진노 아래 있으며, 자신의 의로 거룩하신 하나님 앞에 당당히 설 수 있는 사람은 아무도 없습니다.

④ 구원에 대하여

성경이 구원에 관하여 분명히 말하는 사실이 있습니다. 사람은 자기 자신을 스스로 구원할 수 없습니다. 인간은 죄인으로 태어나며 자신의 힘으로 죄의 지배에서 벗어날 수 없습니다. 착하게 살려고 노력하거나, 종교적 행위로 공로를 쌓거나, 깊은 깨달음을 얻는다고 해도 그것이 하나님 앞에서 구원받을 자격을 만들어 주지는 못합니다.

믿지 않는 사람도 이웃을 돕고 사회에 유익한 일을 할 수 있습니다. 그러한 행동은 사람들에게 실제적인 유익을 줍니다. 그러나 어떤 선행도 이미 지은 죄를 씻거나 하나님 앞에서 의롭다 함을 받을 공로가 될 수 없습니다. 사람의 마음과 동기까지 하나님을 온전히 사랑하고 그분의 영광만을 구하지 못하기 때문입니다.

구원이란 죄의 책임과 영원한 형벌에서 건짐을 받고, 죄의 지배에서 해방되어 하나님과 화목하며 영원한 생명을 얻는 것입니다. 이 구원은 죽음 이후의 소망만을 뜻하지 않습니다. 지금 이 세상에서도 하나님의 자녀로 살아가며, 장차 몸의 부활과 새 하늘과 새 땅의 완성을 기다리는 삶을 포함합니다.

이 구원은 사람의 노력이나 공로로 얻어지는 것이 아니라 오직 하나님의 은혜로 주어집니다.

⑤ 구원자 예수 그리스도

성경은 사랑의 하나님께서 베푸신 유일한 구원의 길을 보여 줍니다. 그 길은 바로 예수 그리스도이십니다. 약 이천 년 전에 이 땅에 오신 예수님은 성부 하나님과 동일한 신성을 지니신 성자 하나님이시며, 동시에 참된 인간이 되신 분입니다.

예수님은 이 땅에서 죄 없이 완전한 삶을 사시고 하나님께 온전히 순종하셨습니다. 첫 사람 아담의 불순종으로 죄와 죽음이 들어온 것과 달리, 마지막 아담이신 예수님은 완전한 순종으로 자기 백성을 위한 의를 이루셨습니다.

예수님은 죄가 없으신 의로운 분이셨지만 십자가에서 우리의 죄책을 대신 담당하셨습니다. 성경이 그분이 “우리를 위하여 죄가 되셨다”라고 말하는 것은 예수님 자신이 죄인이 되셨다는 뜻이 아닙니다. 우리의 죄를 짊어지고 죄를 위한 희생 제물이 되셨다는 뜻입니다. 하나님께서는 그리스도의 완전한 의를 믿는 자에게 전가하십니다.

예수 그리스도께서 우리의 구원자가 되시는 것은 그분의 죽으심으로 우리의 죄값을 완전히 담당하셨고, 그분의 부활로 죄와 죽음을 이기시며 그 속죄가 완성되었음을 확증하셨기 때문입니다. 하나님께서는 이 그리스도를 믿는 자의 죄를 용서하시고, 그리스도의 의를 입혀 의로운 자로 받아들이십니다.

이것을 “칭의(Justification)”라고 합니다. 칭의란 하나님께서 죄인의 죄를 용서하시고 그리스도의 의를 그에게 전가하셔서, 그를 의로운 자로 받아들이시는 단번의 법정적 선언입니다. 칭의에 대해서는 갓플리징 소책자 시리즈 03에서 더 자세히 다룹니다.

⑥ 구원에 이르는 방법

성경은 “주 예수를 믿으라 그리하면 너와 네 집이 구원을 받으리라”라고 선언합니다. 우리의 죄를 대신하여 십자가에 못 박혀 죽으시고 다시 살아나신 예수님은 구주이며 주님이십니다. 그분을 믿는다는 것은 단순히 입술로 “믿겠다”라고 말하거나 어떤 종교 의식을 행하는 것이 아닙니다.

예수님을 믿는다는 것은 그분이 참 하나님이며 참 사람이심을 믿고, 그분의 죽으심이 내가 받아야 할 형벌을 대신 담당하신 대속의 죽음임을 의지하며, 살아 계신 그리스도께 자신을 맡기는 것입니다. 예수님은 우리가 받아들일 때 비로소 주님이 되시는 분이 아니라 본래 모든 사람의 주님이십니다. 믿음은 그분을 자신의 유일한 구원자와 주님으로 인정하고 의지하는 것입니다.

