การชำระให้บริสุทธิ์ไม่ใช่เงื่อนไขเพื่อให้ได้รับความรอด แต่เป็นการเปลี่ยนแปลงที่พระวิญญาณบริสุทธิ์ทรงกระทำภายในผู้ที่พระเจ้าทรงช่วยให้รอดแล้วโดยพระคุณ อย่างไรก็ตาม ผู้เชื่อไม่ได้อยู่นิ่ง ๆ แต่พึ่งพระวิญญาณ ประหารบาป เชื่อฟังพระวจนะ และแสวงหาความบริสุทธิ์อย่างจริงจัง

การต่อสู้กับบาปอาจยาวนานและเจ็บปวด แต่ไม่ใช่การต่อสู้เพื่อหลีกหนีการพิพากษา หากเป็นการต่อสู้ด้วยความเชื่อของผู้ที่ได้รับการยอมรับแล้วในพระคริสต์ และกำลังเดินไปสู่เสรีภาพและความยินดี

บทที่ 1 การชำระให้บริสุทธิ์คืออะไร

การชำระให้บริสุทธิ์คือพระราชกิจแห่งพระคุณที่พระเจ้าทรงใช้พระวิญญาณเปลี่ยนผู้เชื่อใหม่ ทำให้อำนาจของบาปอ่อนกำลังลงทีละน้อย และทำให้เขาเป็นเหมือนพระคริสต์มากขึ้นในความคิด จิตใจ และการกระทำ

การทรงนับว่าเป็นผู้ชอบธรรมกับการชำระให้บริสุทธิ์แตกต่างกัน แต่แยกจากกันไม่ได้ ในการทรงนับว่าเป็นผู้ชอบธรรม พระเจ้าทรงประกาศคนบาปให้ชอบธรรมครั้งเดียว โดยอาศัยความชอบธรรมของพระคริสต์ ส่วนในการชำระให้บริสุทธิ์ พระวิญญาณทรงเปลี่ยนชีวิตจริงของผู้นั้นตลอดชีวิต

การทรงนับว่าเป็นผู้ชอบธรรมสมบูรณ์และไม่เกิดซ้ำ แต่การชำระให้บริสุทธิ์ยังไม่สมบูรณ์และดำเนินไปทีละน้อย ความมั่นใจในความรอดไม่ได้ตั้งอยู่บนระดับความสำเร็จของการชำระให้บริสุทธิ์ แต่ตั้งอยู่บนความชอบธรรมอันสมบูรณ์ของพระคริสต์ อย่างไรก็ตาม ผู้ที่ได้รับการทรงนับว่าเป็นผู้ชอบธรรมจริงย่อมมีผลของการชำระให้บริสุทธิ์

การชำระให้บริสุทธิ์ไม่ได้เกิดจากกำลังใจของมนุษย์เพียงอย่างเดียว พระวิญญาณทรงทำให้เราปรารถนาและสามารถทำตามพระประสงค์ แต่ในเวลาเดียวกัน พระเจ้าก็ทรงบัญชาให้เราหลีกหนีบาป เรียนพระวจนะ อธิษฐาน และถวายกายใจเป็นเครื่องมือแห่งความชอบธรรม

ดังนั้น การชำระให้บริสุทธิ์ไม่ใช่ท่าทีเฉื่อยชาที่ว่า “พระเจ้าจะทำเอง ฉันไม่ต้องทำอะไร” และไม่ใช่การช่วยตนเองด้วยคำว่า “ฉันจะเปลี่ยนตนด้วยกำลังของฉัน” แต่เป็นชีวิตที่เชื่อฟังอย่างจริงจังโดยพึ่งฤทธิ์เดชของพระวิญญาณ

บทที่ 2 เหตุใดคริสเตียนยังต้องต่อสู้กับบาป

ผู้ที่บังเกิดใหม่ได้รับจิตใจใหม่และทิศทางชีวิตใหม่ แต่ตราบใดที่ยังอยู่ในโลกนี้ เศษเหลือของบาปยังคงอยู่ บาปไม่ใช่กษัตริย์ที่ครอบงำผู้เชื่ออีกต่อไป แต่ยังคงเป็นศัตรูที่ล่อลวง หลอกลวง และขัดขวางการเชื่อฟัง

เมื่อพระคัมภีร์กล่าวว่าผู้ที่เกิดจากพระเจ้าไม่ทำบาป ไม่ได้หมายความว่าเขาไม่เคยทำบาปเลย แต่หมายความว่าเขาไม่ยอมรับบาปอย่างไม่ใส่ใจ และไม่ดำเนินชีวิตต่อไปภายใต้อำนาจของมัน

ผู้เชื่อแท้อาจล้มอย่างหนักและอาจทำบาปเดิมซ้ำได้ แต่พระวิญญาณไม่ทรงปล่อยให้เขาชินชากับบาป พระองค์ทรงทำให้ตระหนัก กลับใจ และกลับมาหาพระคริสต์เพื่อต่อสู้อีกครั้ง

การต่อสู้กับบาปไม่ใช่รากฐานของความรอด แต่เป็นผลสำคัญที่แสดงว่ามีชีวิตใหม่ การเสียใจและเกลียดบาป รวมทั้งความปรารถนาจะเชื่อฟังพระเจ้า เป็นหมายสำคัญว่าพระวิญญาณกำลังทรงทำงาน

ผู้เชื่อไม่ควรอ้างว่าตนถึงสภาพไร้บาปในโลกนี้ แต่ควรสารภาพบาปและพึ่งพระคุณทุกวัน ในขณะเดียวกันก็ไม่ควรแก้ตัวว่า “ฉันเป็นคนแบบนี้แหละ” เพื่ออยู่กับบาปต่อไป

บทที่ 3 การประหารบาปคืออะไร

การประหารบาปคือการที่เราพึ่งฤทธิ์เดชของพระวิญญาณ ทำให้ความปรารถนา นิสัย และอำนาจของบาปที่ยังเหลืออยู่ภายในอ่อนกำลังลง และไม่ยอมเชื่อฟังมัน เมื่อพระคัมภีร์สั่งให้ประหารการกระทำของกาย ไม่ได้หมายถึงการทำร้ายร่างกายหรือถือว่าร่างกายเป็นสิ่งชั่วร้าย

หัวใจของการต่อสู้ฝ่ายวิญญาณไม่ได้อยู่ที่การใช้ถ้อยคำพิเศษเพื่อผูกมัดซาตานเท่านั้น แม้เราไม่ควรประมาทการล่อลวงของวิญญาณชั่ว แต่ศัตรูที่ใกล้ที่สุดซึ่งต้องต่อสู้ทุกวันคือบาปภายในตนเอง

การประหารบาปไม่ใช่เพียงหยุดพฤติกรรมชั่วที่เห็นภายนอกชั่วคราว เราต้องสำรวจความอยาก ความกลัว ความหยิ่ง ความไม่เชื่อ และการรักตนเองที่อยู่เบื้องหลัง หากไม่จัดการราก บาปเดียวกันจะกลับมาในรูปร่างอื่น

การเสียใจหรืออับอายเพียงอย่างเดียวไม่เพียงพอ คนอาจเสียใจเพราะถูกจับได้หรือเสียประโยชน์ แต่ไม่ได้เกลียดบาปที่ต่อต้านพระเจ้า การกลับใจแท้หันจากบาปกลับมาหาพระเจ้า

การแทนที่บาปหนึ่งด้วยอีกบาปหนึ่งก็ไม่ใช่การประหารบาป คนอาจกดความโกรธเพื่อให้คนอื่นยอมรับ หรือควบคุมความโลภด้วยความหยิ่ง เป้าหมายไม่ใช่เพียงเป็นคนดูเรียบร้อยขึ้น แต่คือรักพระเจ้าและเชื่อฟังพระองค์ด้วยความยินดี

พร้อมกับการประหารบาป เราต้องดำเนินชีวิตของคนใหม่อย่างจริงจัง ไม่เพียงหยุดโกหกแต่พูดความจริง ไม่เพียงหยุดขโมยแต่ช่วยผู้ขัดสน ไม่เพียงกดความโกรธแต่ปฏิบัติความรักและการให้อภัย

บทที่ 4 จะต่อสู้กับบาปอย่างไร

ไม่มีสูตรลับที่กำจัดทุกปัญหาได้ในครั้งเดียว ผู้เชื่อต้องใช้หนทางแห่งพระคุณต่อไปนี้อย่างสม่ำเสมอ

1. ยอมรับบาปอย่างเฉพาะเจาะจง

อย่าพูดเพียงกว้าง ๆ ว่า “ฉันเป็นคนบาป” แต่จงพิจารณาอย่างซื่อสัตย์ว่า ในสถานการณ์ใด ความปรารถนาใดนำไปสู่บาปอะไร อย่าปกปิดหรือเรียกบาปด้วยชื่อที่ฟังเบาลง แต่เรียกตามที่พระคัมภีร์เรียก

2. ตัดช่องทางของการล่อลวง

สังเกตว่าคุณล้มง่ายเมื่อใด ที่ไหน กับใคร และในสภาพอารมณ์แบบใด การหลีกเลี่ยงสิ่งแวดล้อมและนิสัยที่กระตุ้นบาปไม่ใช่ความเชื่ออ่อน แต่เป็นการเชื่อฟังอย่างมีปัญญา จัดการสิ่งของ สถานที่ แอป ความสัมพันธ์ และการใช้เวลาที่ทำให้ล้มซ้ำจริง ๆ

3. ตรวจสอบความคิดและความปรารถนาด้วยพระวจนะ

บาปเติบโตในความคิดและความปรารถนาก่อนปรากฏเป็นการกระทำ จงค้นพบข้อแก้ตัวและคำโกหกในใจ แล้วตอบโต้ด้วยความจริงของพระคัมภีร์ อย่าปล่อยความคิดว่า “แค่นี้ไม่เป็นไร” “ฉันเป็นฝ่ายถูกกระทำ จึงทำได้” หรือ “ไม่มีใครรู้” ไว้โดยไม่ตรวจสอบ

4. พึ่งพระวิญญาณและอธิษฐาน

อย่าวางใจเพียงความตั้งใจของตน แต่เมื่อรู้สึกถูกล่อลวง จงขอความช่วยเหลือจากพระเจ้าทันที เมื่อพระวิญญาณทรงชี้ให้เห็นบาป อย่าผัดวัน การอธิษฐานไม่ใช่เพียงการเตรียมตัวก่อนต่อสู้ แต่เป็นส่วนหนึ่งของการต่อสู้จริง

5. มองที่พระคริสต์และข่าวประเสริฐ

หากมองเพียงความล้มเหลวของตน เราจะสิ้นหวังหรือกลายเป็นคนหน้าซื่อใจคด จงระลึกว่าพระคริสต์ทรงรับโทษของบาปและทรงทำลายอำนาจของบาป เราไม่ได้ต่อสู้เพื่อให้พระเจ้ารัก แต่ต่อสู้ภายในความรักที่ได้รับแล้ว

6. ปฏิบัติการเชื่อฟังที่ตรงข้ามกับบาป

อย่าหยุดเพียงหลีกเลี่ยงบาป แต่จงทำความดีที่ตรงข้าม หากต่อสู้กับความโลภ จงแบ่งปัน หากต่อสู้กับความหยิ่ง จงรับใช้ หากต่อสู้กับความคิดลามก จงมองผู้อื่นว่าเป็นผู้ที่ทรงสร้างตามพระฉายา หากต่อสู้กับความเกลียด จงให้อภัยและอวยพรอย่างเป็นรูปธรรม

7. เมื่อล้ม จงกลับใจทันทีและเริ่มใหม่

อย่ามองความล้มเหลวเป็นเรื่องเล็ก แต่ก็อย่าหนีจากพระเจ้าเพราะความล้มเหลว จงสารภาพบาป และเมื่อจำเป็นให้ขอโทษหรือแก้ไขความเสียหาย แม้ล้มในบาปเดิมหลายครั้ง ก็อย่าประนีประนอมกับบาป แต่กลับมาที่พระที่นั่งแห่งพระคุณอีกครั้ง

