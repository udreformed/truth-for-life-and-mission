หนังสือเล่มเล็กนี้อธิบาย “ข่าวประเสริฐ” หรือข่าวดีที่พระคัมภีร์ประกาศอย่างง่ายและชัดเจน

ท่านเข้าใจข่าวประเสริฐของพระเยซูคริสต์อย่างชัดเจนแล้วหรือยัง

หากยัง ขอให้ค่อย ๆ อ่านและพิจารณาด้วยใจจริง

ในสังคมไทย เราเติบโตท่ามกลางความเชื่อหลายแบบ บางคนทำตามศาสนาของครอบครัว บางคนทำบุญเพื่อหวังผลดีในชีวิตหรือชาติหน้า บางคนพกเครื่องราง ดูฤกษ์ ดูดวง หรือขอความคุ้มครองจากสิ่งศักดิ์สิทธิ์ บางคนไม่เชื่อเรื่องพระเจ้าและพึ่งเงิน ความสามารถ หรือความดีของตนเอง แต่เรื่องความตาย ความผิดบาป การพิพากษา และชีวิตนิรันดร์ ไม่อาจตัดสินด้วยความคุ้นเคย ความสบายใจ หรือธรรมเนียมที่สืบต่อกันมา คำถามสำคัญคือ สิ่งใดเป็นความจริงจริง ๆ

(1) ศาสนาหรือความเชื่อรับประกันชีวิตหลังความตายได้หรือไม่

หลายคนหวังว่าศาสนาจะช่วยให้ชีวิตราบรื่น ปลอดภัย และได้รับพร บางคนพบกำลังใจจากคำสอนทางศาสนา และบางคนก็ทำความดี ช่วยเหลือเพื่อนบ้าน หรือดูแลคนยากจน สิ่งเหล่านี้อาจก่อประโยชน์ต่อสังคมจริง แต่การที่คำสอนหนึ่งช่วยให้คนอยู่ร่วมกันดีขึ้น ไม่ได้แปลว่าคำสอนนั้นสามารถลบความผิดบาป รับรองชีวิตหลังความตาย หรือทำให้เราถูกต้องต่อพระเจ้าได้

ระบบศาสนาและปรัชญาที่มนุษย์สร้างขึ้นย่อมอยู่ภายในขอบเขตประสบการณ์และความคิดของมนุษย์ ต่อให้มีประเพณียาวนาน หลักคิดลึกซึ้ง หรือประสบการณ์ลึกลับ ก็ยังไม่อาจพิสูจน์ได้อย่างแน่นอนว่า หลังความตายเกิดอะไรขึ้น และมนุษย์จะรอดพ้นจากการพิพากษาได้อย่างไร

ความเชื่อเรื่องการเวียนว่ายตายเกิดอธิบายว่า คนตายแล้วเกิดใหม่ตามกรรม แต่ไม่มีมนุษย์คนใดสามารถกลับมารับรองเรื่องนี้ด้วยอำนาจของตนเองได้ โลกและประวัติศาสตร์หมุนเวียนไปอย่างไม่มีจุดหมายจริงหรือ หรือมีพระผู้สร้างผู้ทรงเริ่มต้นประวัติศาสตร์และจะทรงพิพากษาโลกในที่สุด

ไม่ว่าครู ศาสดา หรือนักปราชญ์จะยิ่งใหญ่เพียงใด มนุษย์ก็ไม่สามารถควบคุมโลกหลังความตายได้ ชะตานิรันดร์ของเราไม่ควรถูกฝากไว้กับสิ่งที่มนุษย์เพียงคาดคะเน ค้นพบ หรือสืบทอดต่อกันมา

(2) พระเจ้าผู้ทรงสร้างโลกและมนุษย์

ถ้ามีพระเจ้าผู้ทรงสร้างโลกและมนุษย์จริง พระองค์เท่านั้นที่ทรงมีสิทธิและทรงสามารถบอกเราได้อย่างแท้จริงว่า ชีวิตมีความหมายอย่างไร ความตายคืออะไร และหลังความตายจะเกิดอะไรขึ้น

บางคนกล่าวว่าไม่มีทางรู้ได้ว่าพระเจ้ามีจริงหรือไม่ เพราะแต่ละศาสนาพูดถึงสิ่งสูงสุดต่างกัน บางคนคิดว่าเพียงมีใจดีและเคารพทุกความเชื่อก็เพียงพอ บางคนเชื่อว่าไม่จำเป็นต้องมีพระเจ้า แต่การคาดเดาของมนุษย์ไม่ว่าจะเป็นฝ่ายใดก็ไม่อาจให้คำตอบที่แน่นอนได้

หากพระผู้สร้างมีจริง พระองค์ต้องทรงเปิดเผยพระองค์เองก่อน มนุษย์ผู้มีขอบเขตไม่อาจปีนขึ้นไปค้นพบพระเจ้าผู้ไม่มีขอบเขตด้วยกำลังของตน พระคัมภีร์ยืนยันว่า พระเจ้าทรงโน้มพระองค์ลงมาและทรงเปิดเผยพระองค์ด้วยพระวจนะที่มนุษย์เข้าใจได้

(3) พระวจนะที่พระเจ้าทรงเปิดเผยเป็นพิเศษ

มีหนังสือเล่มหนึ่งที่กล่าวถึงจุดเริ่มต้นและจุดจบของโลก ความตาย การพิพากษา และชีวิตนิรันดร์อย่างชัดเจน หนังสือนั้นคือพระคัมภีร์ พระคัมภีร์ประกาศว่า พระเจ้านิรันดร์ทรงสร้างทุกสิ่ง และมนุษย์กับประวัติศาสตร์ทั้งหมดอยู่ในพระหัตถ์ของพระองค์ พระคัมภีร์ยังอธิบายว่าเหตุใดโลกจึงเต็มไปด้วยความเจ็บปวด ความชั่ว และความอยุติธรรม และมนุษย์ต้องได้รับความรอดจากอะไร

พระคัมภีร์ประกอบด้วยหนังสือหกสิบหกเล่ม เขียนขึ้นในหลายยุคสมัย โดยผู้เขียนหลายคนที่มีพื้นเพต่างกัน แต่ทั้งหมดเล่าเรื่องเดียวกันอย่างต่อเนื่อง คือการทรงสร้าง การล้มลงในบาป การพิพากษา และความรอดที่พระเจ้าทรงทำให้สำเร็จในพระเยซูคริสต์ ความเป็นหนึ่งเดียวนี้ชี้ให้เห็นว่าพระเจ้าองค์เดียวทรงเปิดเผยแผนการแห่งความรอดของพระองค์

พระคัมภีร์มีอำนาจ ไม่ใช่เพียงเพราะเป็นหนังสือเก่าแก่หรือมีคนอ่านมาก แต่เพราะพระคัมภีร์เป็นพยานถึงตนเองว่าเป็นพระวจนะของพระเจ้า และคำสัญญาต่าง ๆ มุ่งไปสู่ความสำเร็จในพระเยซูคริสต์ พระวิญญาณบริสุทธิ์ทรงใช้พระวจนะนี้เพื่อทำให้มนุษย์ตระหนักถึงความจริงและสิทธิอำนาจของพระเจ้า

ดังนั้น พระคัมภีร์ไม่ใช่เพียงหนังสือที่เสนอแนวคิดทางศาสนาอีกแบบหนึ่ง แต่เป็นพระวจนะที่พระเจ้าประทานแก่มนุษย์ทั้งโลก

(4) พระคัมภีร์กล่าวว่าอย่างไร

ต่อไปนี้คือสาระสำคัญที่พระคัมภีร์สอนเกี่ยวกับพระเจ้า มนุษย์ การพิพากษา และความรอด ซึ่งมนุษย์ไม่อาจค้นพบได้ด้วยความคิดของตนเอง

① เกี่ยวกับพระเจ้า

หนังสือปฐมกาลเริ่มต้นด้วยคำประกาศว่า “ในปฐมกาล พระเจ้าทรงเนรมิตสร้างฟ้าและแผ่นดิน” พระคัมภีร์ไม่ได้มีจุดประสงค์เป็นตำราวิทยาศาสตร์ที่อธิบายทุกขั้นตอนของการสร้าง แต่ประกาศความจริงพื้นฐานที่สุดว่า พระเจ้าทรงเป็นพระผู้สร้างผู้ทรงฤทธานุภาพ ผู้ทรงสร้างทั้งสิ่งที่มองเห็นและมองไม่เห็น

พระเจ้าทรงเป็นพระวิญญาณนิรันดร์ ไม่มีจุดเริ่มต้นหรือจุดจบ ทรงบริสุทธิ์ ดี และยุติธรรม พระปัญญา ความรู้ ความรัก และฤทธานุภาพของพระองค์ไม่มีขอบเขต

พระเจ้าไม่ใช่เทพองค์หนึ่งท่ามกลางเทพหลายองค์ ไม่ใช่วิญญาณประจำถิ่น และไม่ต้องอาศัยเครื่องราง สถานที่ หรือพิธีกรรมใด ๆ พระองค์ทรงเป็นพระผู้สร้างและองค์อธิปัตย์เหนือทุกสิ่ง จึงทรงสมควรได้รับพระเกียรติและการนมัสการแต่เพียงผู้เดียว

② เกี่ยวกับมนุษย์

พระคัมภีร์สอนว่า พระเจ้าทรงสร้างมนุษย์อย่างพิเศษตามพระฉายาของพระองค์ มนุษย์จึงสามารถคิด ตัดสินใจ รับผิดชอบ รู้จักพระเจ้า รักพระองค์ และเชื่อฟังพระประสงค์ของพระองค์ เสรีภาพของมนุษย์ไม่ใช่เสรีภาพที่เป็นอิสระจากพระผู้สร้าง แต่เป็นเสรีภาพของผู้ถูกสร้างที่ต้องรับผิดชอบต่อพระองค์

อย่างไรก็ตาม มนุษย์สูญเสียสภาพที่ดีดั้งเดิมในอาดัม มนุษย์คนแรก อาดัมฝ่าฝืนคำสั่งของพระเจ้าโดยกินผลจากต้นไม้ที่พระเจ้าทรงห้าม นี่ไม่ใช่เพียงความผิดพลาดเล็กน้อย แต่เป็นการกบฏต่อพระเจ้าและต้องการเป็นนายเหนือชีวิตของตนเอง ผลคือบาป ความตายฝ่ายกาย และความตายฝ่ายวิญญาณเข้าสู่มนุษยชาติ

พระคัมภีร์กล่าวอย่างชัดเจนว่า มนุษย์ทุกคนเป็นคนบาป บาปไม่ใช่เพียงการทำผิดกฎหมายหรือทำสิ่งที่สังคมมองว่าไม่ดี แต่รวมถึงการไม่ยอมรับพระเจ้าเป็นองค์พระผู้เป็นเจ้า และยกตนเองขึ้นเป็นศูนย์กลางของชีวิต มนุษย์ทุกคนเกิดมาพร้อมธรรมชาติที่เสื่อมทรามและไม่สามารถกลับมารักพระเจ้าหรือช่วยตนเองให้รอดได้

③ เกี่ยวกับการพิพากษา

หลังจากอาดัม มนุษย์ทุกคนดำเนินชีวิตโดยฝ่าฝืนพระประสงค์ของพระเจ้า เราอาจมองตนเองว่าเป็นคนธรรมดาหรือเป็นคนดีกว่าบางคน แต่พระเจ้าทรงมองเห็นทั้งการกระทำ ความคิด และแรงจูงใจที่ซ่อนอยู่

เพราะการล้มลงในบาป โลกจึงอยู่ภายใต้ความทุกข์ ความเสื่อม และความตาย แต่เราไม่ควรสรุปว่าโรคภัย อุบัติเหตุ หรือความยากจนของคนหนึ่งเป็นผลตรงจากบาปเฉพาะอย่างหรือ “กรรมตามสนอง” ของคนนั้นเสมอไป ความทุกข์ทั้งหมดชี้ว่าโลกที่หันจากพระเจ้าถูกทำลายโดยบาป และมนุษย์ทุกคนจะต้องยืนต่อหน้าการพิพากษาของพระเจ้า

ความตายไม่ใช่จุดจบของทุกสิ่ง และไม่ใช่ประตูสู่วงจรการเกิดใหม่ พระคัมภีร์สอนว่า หลังความตายมนุษย์ต้องรับการพิพากษา และผู้ที่อยู่นอกพระคริสต์จะต้องรับโทษแห่งการแยกจากพระเจ้านิรันดร์

การพิพากษาของพระเจ้าไม่ใช้มาตรฐานผิวเผินแบบมนุษย์ พระองค์ทรงรู้ทุกความคิด ทุกแรงจูงใจ และทุกการกระทำ พระองค์ทรงพิพากษาอย่างยุติธรรมแม้กระทั่งการที่มนุษย์ไม่รักพระผู้สร้างและไม่ถวายพระเกียรติแด่พระองค์ตามที่ควร

ดังนั้น มนุษย์ทุกคนอยู่ภายใต้พระพิโรธอันชอบธรรมของพระเจ้า และไม่มีใครยืนต่อหน้าพระเจ้าผู้บริสุทธิ์ได้ด้วยความชอบธรรมของตนเอง

④ เกี่ยวกับความรอด

พระคัมภีร์ประกาศว่า มนุษย์ไม่สามารถช่วยตนเองให้รอดได้ เราไม่อาจหลุดพ้นจากอำนาจบาปด้วยการฝึกใจ การถือศีล การบำเพ็ญตน การทำพิธี หรือการสะสมบุญ แม้การกระทำเหล่านั้นจะทำให้เรารู้สึกดีขึ้นหรือได้รับคำชมจากคนอื่น แต่ก็ไม่สามารถชำระความผิดของเราต่อพระเจ้าได้

ผู้ที่ยังไม่เชื่อพระคริสต์ก็สามารถช่วยเพื่อนบ้าน ดูแลพ่อแม่ หรือทำประโยชน์ต่อสังคมได้ และสิ่งเหล่านี้มีคุณค่าต่อผู้คนจริง แต่ความดีไม่ใช่เงินที่นำไปชำระหนี้บาป และไม่ทำให้พระเจ้ามีหน้าที่ต้องตอบแทนเราด้วยความรอด หัวใจและแรงจูงใจของเรายังไม่รักพระเจ้าอย่างสมบูรณ์และยังไม่แสวงหาพระเกียรติของพระองค์แต่ผู้เดียว

ความรอดคือการได้รับการช่วยให้พ้นจากความผิดและโทษนิรันดร์ หลุดพ้นจากอำนาจของบาป กลับคืนดีกับพระเจ้า และได้รับชีวิตนิรันดร์ ความรอดไม่ใช่เพียงความหวังหลังความตาย แต่คือการเป็นบุตรของพระเจ้าในปัจจุบัน และรอคอยการเป็นขึ้นจากตายของร่างกายกับฟ้าใหม่และแผ่นดินโลกใหม่

ความรอดนี้ไม่ได้มาจากความพยายามหรือบุญกุศลของมนุษย์ แต่เป็นพระคุณที่พระเจ้าประทานโดยไม่คิดราคา

⑤ พระเยซูคริสต์ พระผู้ช่วยให้รอด

พระคัมภีร์เปิดเผยหนทางแห่งความรอดเพียงทางเดียวที่พระเจ้าผู้ทรงรักทรงจัดเตรียม คือพระเยซูคริสต์ พระองค์ทรงเป็นพระบุตรผู้มีสภาพพระเจ้าเช่นเดียวกับพระบิดา และเมื่อประมาณสองพันปีก่อนทรงรับสภาพมนุษย์อย่างแท้จริง

พระเยซูทรงดำเนินชีวิตโดยปราศจากบาปและเชื่อฟังพระเจ้าอย่างสมบูรณ์ ต่างจากอาดัมคนแรกผู้ไม่เชื่อฟัง พระเยซูผู้เป็นอาดัมคนสุดท้ายทรงทำให้ความชอบธรรมสำเร็จเพื่อประชากรของพระองค์

แม้พระเยซูทรงชอบธรรมและไม่มีบาป พระองค์ทรงรับความผิดของเราไว้บนไม้กางเขน เมื่อพระคัมภีร์กล่าวว่าพระองค์ “ทรงถูกทำให้เป็นบาปเพื่อเรา” ไม่ได้หมายความว่าพระเยซูกลายเป็นคนบาป แต่หมายความว่าพระองค์ทรงแบกความผิดของเราและถวายพระองค์เป็นเครื่องบูชาไถ่บาป พระเจ้าทรงนับความชอบธรรมที่สมบูรณ์ของพระคริสต์ให้แก่ผู้ที่เชื่อ

พระเยซูทรงเป็นพระผู้ช่วยให้รอด เพราะการสิ้นพระชนม์ของพระองค์ชำระโทษบาปของเราอย่างครบถ้วน และการเป็นขึ้นจากตายยืนยันว่าการไถ่สำเร็จแล้วและพระองค์ทรงมีชัยเหนือบาปกับความตาย พระเจ้าทรงยกโทษผู้ที่วางใจในพระคริสต์ และทรงรับเขาเป็นผู้ชอบธรรมเพราะความชอบธรรมของพระคริสต์

สิ่งนี้เรียกว่า “การทรงนับว่าเป็นผู้ชอบธรรม” (Justification) คือการประกาศของพระเจ้าในฐานะผู้พิพากษาเพียงครั้งเดียวว่า บาปของผู้เชื่อได้รับการอภัย และความชอบธรรมของพระคริสต์ถูกนับเป็นของเขา หัวข้อนี้จะอธิบายละเอียดขึ้นในหนังสือเล่มเล็กชุดที่ 03

⑥ มนุษย์รับความรอดได้อย่างไร

พระคัมภีร์ประกาศว่า “จงเชื่อในพระเยซูองค์พระผู้เป็นเจ้า แล้วท่านจะได้รับความรอด” พระเยซูผู้ทรงถูกตรึงตายแทนเราและทรงเป็นขึ้นจากตาย คือพระผู้ช่วยให้รอดและองค์พระผู้เป็นเจ้า การเชื่อไม่ใช่เพียงพูดว่า “ฉันเชื่อ” เข้าพิธีหนึ่ง หรือเพิ่มพระเยซูเข้าไปเป็นสิ่งศักดิ์สิทธิ์อีกองค์หนึ่งข้างสิ่งที่เราเคารพอยู่เดิม

การเชื่อพระเยซูหมายถึงเชื่อว่าพระองค์ทรงเป็นพระเจ้าแท้และมนุษย์แท้ วางใจว่าการสิ้นพระชนม์ของพระองค์รับโทษแทนเรา และมอบตนไว้กับพระคริสต์ผู้ทรงพระชนม์ พระเยซูไม่ได้ทรงเป็นองค์พระผู้เป็นเจ้าเพราะเราอนุญาต แต่ทรงเป็นองค์พระผู้เป็นเจ้าเหนือทุกคนอยู่แล้ว ความเชื่อแท้คือการยอมรับและพึ่งพระองค์เป็นพระผู้ช่วยให้รอดและองค์พระผู้เป็นเจ้าแต่เพียงผู้เดียว

ความเชื่อแท้มาพร้อมการกลับใจ การกลับใจไม่ใช่เพียงเสียใจ กลัวผลกรรม หรือทำพิธีชดเชย แต่คือการยอมรับว่าเราได้หันจากพระเจ้าและใช้ชีวิตเป็นนายของตนเอง แล้วหันจากบาปกลับมาหาพระเจ้า

ความเชื่อและการกลับใจไม่ใช่บุญหรือราคาที่เราจ่ายเพื่อซื้อความรอด รากฐานเดียวของความรอดคือความชอบธรรมที่สมบูรณ์ของพระเยซูคริสต์ ความเชื่อคือหนทางที่พระเจ้าทรงกำหนดให้เรารับพระคริสต์และความรอด และความเชื่อนี้ก็เป็นของประทานแห่งพระคุณจากพระวิญญาณบริสุทธิ์

ความเชื่อแท้ไม่อยู่โดดเดี่ยว ผู้ที่พระเจ้าทรงนับว่าเป็นผู้ชอบธรรมจะเริ่มเกิดผลแห่งความรักและการเชื่อฟังโดยการทำงานของพระวิญญาณ ความดีไม่ใช่ราคาของความรอด แต่เป็นผลของความรอดที่ได้รับแล้ว

⑦ พระวิญญาณบริสุทธิ์ทรงนำความรอดมาใช้กับเรา

พระบิดาทรงวางแผนความรอด พระบุตรทรงทำให้ความรอดสำเร็จด้วยไม้กางเขนและการเป็นขึ้นจากตาย และพระวิญญาณบริสุทธิ์ทรงนำความรอดนั้นมาใช้กับคนบาป พระบิดา พระบุตร และพระวิญญาณบริสุทธิ์ทรงเป็นพระเจ้าองค์เดียว และทรงทำงานด้วยพระประสงค์และความรักเดียวกัน

มนุษย์ที่ตายฝ่ายวิญญาณเพราะบาปไม่สามารถเข้าใจข่าวประเสริฐอย่างถูกต้องหรือมาหาพระคริสต์ด้วยกำลังตนเอง เมื่อพระวิญญาณบริสุทธิ์ทรงให้ชีวิตใหม่และเปิดใจ เขาจึงมองเห็นความจริง กลับใจ และเชื่อในพระเยซูคริสต์

พระวิญญาณบริสุทธิ์ทรงผูกผู้เชื่อไว้กับพระคริสต์ ทรงยืนยันว่าเขาเป็นบุตรของพระเจ้า และทรงเปลี่ยนชีวิตผ่านพระวจนะ ความมั่นใจในความรอดตั้งอยู่ก่อนอื่นบนพระราชกิจที่สมบูรณ์ของพระคริสต์และพระสัญญาของพระเจ้า แล้วจึงได้รับการยืนยันมากขึ้นผ่านผลของพระวิญญาณในชีวิต

