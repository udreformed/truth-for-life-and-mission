บาปไม่ใช่เพียงการทำผิดกฎเล็ก ๆ หรือทำคะแนนความดีไม่พอ บาปคือการปฏิเสธสิทธิของพระเจ้าเหนือชีวิตของเรา มนุษย์ต้องการเป็นนายของตนเอง ตัดสินเองว่าอะไรดีอะไรชั่ว และใช้ชีวิตเพื่อความพอใจของตนแทนที่จะถวายเกียรติแด่พระผู้สร้าง

ในวัฒนธรรมที่คุ้นเคยกับการทำบุญ หลายคนคิดว่าความดีภายหลังสามารถลบความผิดในอดีตได้ แต่แม้ในศาลของมนุษย์ การทำความดีหลังจากก่ออาชญากรรมไม่ได้ทำให้ความผิดนั้นหายไป ความยุติธรรมเรียกร้องให้ความผิดได้รับการจัดการอย่างถูกต้อง ยิ่งกว่านั้น พระเจ้าผู้ทรงยุติธรรมอย่างสมบูรณ์ย่อมไม่ทรงเพิกเฉยต่อบาป

ดังนั้น หากคนบาปจะได้รับการยกโทษ โทษของบาปต้องได้รับการชำระอย่างชอบธรรม นี่คือเหตุผลที่กางเขนจำเป็น

แล้วคนบาปจะได้รับการยกโทษได้อย่างไร?

ไม่มีใครชำระบาปของตนด้วยการทำบุญ ถือศีล ปฏิบัติพิธีกรรม บริจาคเงิน ช่วยเหลือผู้อื่น หรือพยายามเป็นคนดี แม้ความดีต่อเพื่อนมนุษย์เป็นสิ่งที่ควรทำ แต่ความดีเหล่านั้นไม่สามารถลบความผิดที่เรามีต่อพระเจ้าได้

พระเจ้าทรงมองไม่เพียงการกระทำภายนอก แต่ทรงเห็นแรงจูงใจภายใน ความดีของเรามักปะปนด้วยความหยิ่ง ความต้องการคำชม ความกลัวผลกรรม หรือความหวังว่าจะได้สิ่งตอบแทน เพราะฉะนั้น แม้การกระทำที่ดูดีในสายตามนุษย์ก็ไม่อาจเป็นความชอบธรรมสมบูรณ์ต่อหน้าพระเจ้าผู้บริสุทธิ์

ความรอดจึงไม่สามารถเริ่มจากมนุษย์ ต้องเริ่มจากพระเจ้า พระองค์ทรงเปิดทางแห่งความรอดด้วยพระเมตตาของพระองค์เอง

พระเยซูคริสต์ทรงเป็นพระเจ้าแท้และมนุษย์แท้ พระองค์ทรงไม่มีบาป ทรงเชื่อฟังพระบัญญัติทุกประการอย่างสมบูรณ์ และทรงยอมสิ้นพระชนม์แทนคนบาป กางเขนจึงเป็นสถานที่ที่ความรักและความยุติธรรมของพระเจ้าปรากฏพร้อมกัน ความยุติธรรมได้รับการตอบสนอง และความรักต่อคนบาปได้รับการสำแดงอย่างสูงสุด

การสิ้นพระชนม์ของพระเยซูบนกางเขนหมายความว่าอะไร?

บางคนมองพระเยซูเพียงเป็นแบบอย่างของความเสียสละและความรัก แน่นอน กางเขนแสดงความรักยิ่งใหญ่ แต่หากเราหยุดเพียงเท่านี้ เราจะพลาดหัวใจของข่าวประเสริฐ

พระเยซูไม่ได้สิ้นพระชนม์เพียงเพื่อสอนให้เรารักผู้อื่น พระองค์สิ้นพระชนม์แทนคนบาป ทรงรับโทษที่คนบาปควรได้รับ นี่เรียกว่า “การไถ่บาปแทน” หรือ “การรับโทษแทน”

พระเยซูทรงเป็นผู้ชอบธรรม ไม่มีบาป แต่ทรงแบกความผิดของประชากรของพระองค์ พระองค์ทรงรับคำสาปและพระพิโรธอันชอบธรรมต่อบาปบนกางเขน

การที่พระคัมภีร์กล่าวว่าพระเยซูทรง “เป็นบาปแทนเรา” ไม่ได้หมายความว่าพระองค์กลายเป็นคนบาป พระองค์ยังทรงบริสุทธิ์เสมอ แต่ความผิดของเราได้ถูกนับไว้กับพระองค์ และพระองค์ทรงรับโทษแทนเรา

พระเยซูทรงเป็นพระบุตรนิรันดร์ของพระเจ้า การถวายพระองค์จึงมีคุณค่าเพียงพอและสมบูรณ์ พระองค์ทรงถวายพระองค์ครั้งเดียว และการไถ่นั้นไม่ต้องทำซ้ำ

กางเขนไม่ได้หมายความว่าพระบิดาไม่รักคนบาป แล้วพระเยซูต้องมาทำให้พระบิดาใจอ่อน ตรงกันข้าม พระบิดาทรงรักและทรงส่งพระบุตร พระบุตรทรงสมัครพระทัยมอบพระองค์ และพระวิญญาณทรงนำแผนความรอดมาใช้กับผู้เชื่อ นี่คือพระราชกิจอันเป็นหนึ่งเดียวของพระเจ้าตรีเอกานุภาพ

พระเยซูไม่ได้อยู่ในความตาย พระองค์ทรงเป็นขึ้นจากตาย การฟื้นคืนพระชนม์ยืนยันว่าการไถ่บาปสำเร็จแล้ว ความตายถูกพิชิต และพระเยซูทรงเป็นองค์พระผู้เป็นเจ้าอย่างแท้จริง

การทรงนับว่าเป็นผู้ชอบธรรมคืออะไร?

“การทรงนับว่าเป็นผู้ชอบธรรม” คือการที่พระเจ้าผู้ทรงเป็นผู้พิพากษา ทรงยกโทษบาปของผู้ที่เชื่อในพระเยซูคริสต์ ทรงนับความชอบธรรมของพระคริสต์เป็นของเขา และทรงประกาศว่าเขาเป็นผู้ชอบธรรมต่อพระพักตร์พระองค์

นี่เป็นคำตัดสินทางกฎหมาย ไม่ใช่การบอกว่าคนนั้นได้กลายเป็นคนสมบูรณ์แบบทันที การเปลี่ยนชีวิตภายในอย่างต่อเนื่องเรียกว่า “การชำระให้บริสุทธิ์” ส่วนการทรงนับว่าเป็นผู้ชอบธรรมคือการเปลี่ยนสถานะของคนบาปต่อหน้าพระเจ้า

เดิมเขาเป็นผู้มีความผิดและอยู่ภายใต้การพิพากษา แต่เมื่อเขาอยู่ในพระคริสต์ พระเจ้าทรงยกโทษและทรงรับเขาในฐานะผู้ชอบธรรม

คนบาปไม่เพียงต้องการให้ความผิดถูกลบ เขายังต้องมีความชอบธรรมสมบูรณ์เพื่อยืนต่อหน้าพระเจ้า ความชอบธรรมนั้นไม่ได้เกิดจากภายในเรา แต่เป็นความชอบธรรมของพระคริสต์ที่พระเจ้าทรงประทานแก่เรา

ความผิดของเราอยู่กับพระคริสต์ และความชอบธรรมของพระคริสต์อยู่กับเรา

ในพันธสัญญาเดิม การถวายสัตว์เป็นเครื่องบูชาเป็นภาพล่วงหน้าของพระคริสต์ ผู้ถวายวางมือบนหัวสัตว์เพื่อแสดงว่าเครื่องบูชานั้นกำลังรับโทษแทน แต่เลือดสัตว์ไม่สามารถลบบาปได้อย่างแท้จริง ทั้งหมดเป็นเงาที่ชี้ไปยังพระเยซู พระเมษโปดกผู้สมบูรณ์

“เราทุกคนหลงทางไปเหมือนแกะ ต่างคนต่างหันไปตามทางของตน แต่พระยาห์เวห์ทรงวางความผิดของเราทุกคนไว้บนพระองค์”
อิสยาห์ 53:6

“พระเจ้าทรงทำให้พระองค์ผู้ไม่ทรงรู้จักบาปเป็นบาปเพราะเรา เพื่อว่าในพระองค์เราจะได้เป็นความชอบธรรมของพระเจ้า”
2 โครินธ์ 5:21

ความผิดของผู้เชื่อถูกนับไว้กับพระคริสต์ และความชอบธรรมสมบูรณ์ของพระคริสต์ถูกนับไว้กับผู้เชื่อ คำว่า “นับไว้” หรือ “โอนให้” หมายถึงการถือสิ่งที่เป็นของคนหนึ่งให้เป็นของอีกคนหนึ่งในทางกฎหมาย

พระเยซูทรงเชื่อฟังพระบิดาตลอดชีวิต อาดัมและมนุษย์ทุกคนล้มเหลว แต่พระคริสต์ทรงเชื่อฟังอย่างสมบูรณ์ ทั้งชีวิตที่เชื่อฟังและการสิ้นพระชนม์แทนเราจึงเป็นรากฐานของการทรงนับว่าเป็นผู้ชอบธรรม

“เพราะการไม่เชื่อฟังของคนคนเดียวทำให้คนเป็นอันมากเป็นคนบาปฉันใด การเชื่อฟังของคนคนเดียวก็จะทำให้คนเป็นอันมากเป็นผู้ชอบธรรมฉันนั้น”
โรม 5:19

พระเจ้าไม่ได้ทรงประกาศว่าเราเป็นผู้ชอบธรรมเพราะเรากลายเป็นคนดีพอ เพราะเรากลับใจแรงพอ หรือเพราะชีวิตเราดีขึ้นมากพอ รากฐานเพียงอย่างเดียวคือพระคริสต์และพระราชกิจของพระองค์

การทรงนับว่าเป็นผู้ชอบธรรมเกิดขึ้นครั้งเดียวและสมบูรณ์ ผู้เชื่อทุกคนได้รับความชอบธรรมเดียวกันในพระคริสต์ แม้ระดับความเติบโตฝ่ายวิญญาณของแต่ละคนไม่เท่ากัน

ผู้ที่ได้รับการประกาศว่าเป็นผู้ชอบธรรมยังต้องต่อสู้กับบาปและเติบโตในความบริสุทธิ์ แต่การที่พระเจ้าทรงยอมรับเขาไม่ได้ขึ้นอยู่กับระดับความสำเร็จของการเติบโตนั้น

“เพื่อพระองค์จะทรงเป็นผู้ชอบธรรม และทรงให้ผู้ที่มีความเชื่อในพระเยซูเป็นผู้ชอบธรรมด้วย”
โรม 3:26

“รอดโดยความเชื่อเท่านั้น” หมายความว่าอะไร?

เมื่อพระคัมภีร์สอนว่าเรารอดโดยความเชื่อ ไม่ได้หมายความว่าความเชื่อของเราเป็นบุญชนิดหนึ่ง หรือเป็นค่าตอบแทนที่พระเจ้าต้องประทานความรอด

ต้นกำเนิดของความรอดคือพระคุณของพระเจ้า รากฐานของความรอดคือความชอบธรรมและการไถ่ของพระคริสต์ ส่วนความเชื่อคือหนทางที่เรารับพระคริสต์และสิ่งที่พระองค์ทรงทำ

ลองคิดถึงพ่อที่ให้รถแก่ลูกเป็นของขวัญ ลูกยื่นมือรับกุญแจ มือไม่ได้ซื้อรถ และการยื่นมือไม่ใช่เหตุผลที่พ่อให้รถ มือเป็นเพียงสิ่งที่รับของขวัญ ความเชื่อก็เช่นเดียวกัน

เราจึงไม่อวดความเชื่อของตน ความเชื่อแท้คือการเลิกพึ่งความดี ความเคร่งศาสนา การทำบุญ หรือความสามารถของตน แล้วพึ่งพระเยซูคริสต์แต่เพียงผู้เดียว

แม้แต่ความเชื่อก็เป็นของประทานแห่งพระคุณ คนที่ตายฝ่ายวิญญาณไม่สามารถทำให้ตนเองเห็นความงามของพระคริสต์ พระวิญญาณบริสุทธิ์ทรงเปิดใจ ให้เข้าใจข่าวประเสริฐ เห็นบาปของตน และวางใจในพระผู้ช่วยให้รอด

ความเชื่อที่ช่วยให้รอดคืออะไร?

ความเชื่อที่ช่วยให้รอดไม่ใช่เพียงการพูดว่า “ฉันเชื่อพระเยซู” ไม่ใช่เพียงการอธิษฐานตามใครสักคนครั้งเดียว และไม่ใช่เพียงประสบการณ์ที่ทำให้รู้สึกตื่นเต้นหรือสงบชั่วคราว

ความเชื่อแท้ประกอบด้วยสามส่วน หนึ่ง รู้เนื้อหาของข่าวประเสริฐ สอง ยอมรับว่าข่าวประเสริฐนั้นเป็นความจริง สาม มอบตนและวางใจในพระเยซูคริสต์

ผู้เชื่อยอมรับพระเยซูไม่เพียงเป็นผู้ช่วยแก้ปัญหา แต่เป็นพระผู้ช่วยให้รอดและองค์พระผู้เป็นเจ้า ในฐานะพระผู้ช่วยให้รอด พระองค์เท่านั้นทรงอภัยบาปและช่วยให้พ้นการพิพากษา ในฐานะองค์พระผู้เป็นเจ้า พระองค์ทรงมีสิทธิสูงสุดเหนือชีวิตของเรา

ความเชื่อแท้แยกจากการกลับใจไม่ได้ การกลับใจไม่ใช่เพียงเสียใจเพราะกลัวผลของบาป แต่เป็นการเปลี่ยนใจต่อบาป หันจากทางของตน และหันกลับมาหาพระเจ้า

ผู้เชื่อแท้ยังอ่อนแอและอาจล้มลงในบาป แต่เขาไม่สามารถอยู่อย่างสงบกับบาปได้ เขาจะถูกนำให้สารภาพ กลับใจ และพึ่งพระคริสต์ใหม่

ความเชื่อของแต่ละคนมีความเข้มแข็งไม่เท่ากัน แต่เราไม่ได้รอดเพราะความเชื่อของเราแข็งแรง เรารอดเพราะพระคริสต์ผู้ที่ความเชื่อนั้นยึดไว้ ความเชื่อที่อ่อนแอซึ่งยึดพระคริสต์แท้ ยังมีค่ามากกว่าความมั่นใจสูงที่ยึดสิ่งผิด

ความเชื่อและการประพฤติเกี่ยวข้องกันอย่างไร?

พระคัมภีร์สอนชัดว่าเราไม่ได้รับการทรงนับว่าเป็นผู้ชอบธรรมด้วยการประพฤติ แต่พระคัมภีร์ก็สอนว่าความเชื่อที่ไม่มีการประพฤติเป็นความเชื่อที่ตายแล้ว สองข้อนี้ไม่ขัดแย้งกัน

การประพฤติดีไม่ใช่รากของความรอด แต่เป็นผลของความรอด เราไม่ได้ทำดีเพื่อให้พระเจ้ารับเรา แต่เพราะพระเจ้าทรงรับเราในพระคริสต์ เราจึงเริ่มดำเนินชีวิตใหม่

การกระทำที่ดีไม่ใช่เหตุให้เกิดการทรงนับว่าเป็นผู้ชอบธรรม แต่เป็นผลจากการบังเกิดใหม่ ผู้ที่ได้รับชีวิตใหม่จะเริ่มรักพระเจ้า เกลียดบาป รักพี่น้อง และปรารถนาจะเชื่อฟังพระคำ

หากไม่มีการเปลี่ยนทิศทางของชีวิตเลย หากคนหนึ่งรักบาปและไม่ต้องการเชื่อฟังพระคริสต์ เขาควรตรวจสอบอย่างจริงจังว่าความเชื่อของตนเป็นความเชื่อแท้หรือไม่

อย่างไรก็ตาม เราไม่ควรนำผลของชีวิตมาเป็นรากฐานสูงสุดของความมั่นใจ ความมั่นใจของผู้เชื่อวางอยู่ก่อนอื่นบนพระสัญญาของพระเจ้าและพระราชกิจสมบูรณ์ของพระคริสต์ ส่วนผลของชีวิตเป็นหลักฐานประกอบว่าพระคุณกำลังทำงานจริง

