죄죽임과 함께 새 사람의 삶도 적극적으로 살아야 합니다. 거짓을 버리는 것에서 끝나지 않고 진실을 말하며, 도둑질을 그치는 것에서 끝나지 않고 필요한 사람을 돕고, 분노를 억누르는 것에서 끝나지 않고 사랑과 용서를 실천해야 합니다.

4장. 죄와 어떻게 싸울 것인가

죄와의 싸움에는 한 번에 모든 문제를 없애는 비밀 공식이 없습니다. 성도는 다음의 은혜로운 방편을 꾸준히 사용하며 싸워야 합니다.

1. 죄를 구체적으로 인정하십시오

막연히 “제가 죄인입니다”라고만 말하지 말고, 어떤 상황에서 어떤 욕망 때문에 어떤 죄를 범했는지 정직하게 살피십시오. 죄를 숨기거나 부드러운 이름으로 바꾸지 말고 성경이 부르는 이름으로 부르십시오.

2. 유혹의 통로를 끊으십시오

