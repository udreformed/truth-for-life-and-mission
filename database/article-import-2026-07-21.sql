죄와의 싸움에서 자신의 실패만 바라보면 절망하거나 위선에 빠집니다. 그리스도께서 죄의 형벌을 담당하셨고 죄의 권세를 깨뜨리셨음을 기억하십시오. 우리는 하나님의 사랑을 얻기 위해 싸우는 것이 아니라, 이미 받은 사랑 안에서 싸웁니다.

6. 반대되는 순종을 실천하십시오

죄를 피하는 데서 멈추지 말고 그 죄와 반대되는 선을 행하십시오. 탐욕과 싸운다면 나누고, 교만과 싸운다면 섬기며, 음란한 생각과 싸운다면 사람을 하나님의 형상으로 존중하고, 미움과 싸운다면 구체적으로 용서하고 축복하십시오.

7. 넘어졌을 때 즉시 회개하고 다시 시작하십시오

실패를 가볍게 여기지 말되, 실패 때문에 하나님에게서 도망치지도 마십시오. 죄를 고백하고 필요한 경우 피해를 입은 사람에게 사과하고 바로잡으십시오. 같은 죄에 여러 번 넘어졌더라도 죄와 화해하지 말고 다시 은혜의 보좌 앞으로 나아가십시오.

5장. 은혜의 수단을 사용하십시오

