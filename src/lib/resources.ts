function sameCalendarDay(resourceDate?: string | null, requestedDate?: string) {
  if (!requestedDate) return true;
  if (!resourceDate) return false;
  if (resourceDate === requestedDate) return true;
  return resourceDate.slice(5, 10) === requestedDate.slice(5, 10);
}

