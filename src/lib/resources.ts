export async function getPublishedResource(
  language: Language,
  slug: string
): Promise<ResourceSummary | null> {
  const staticResource = allStaticResources(language).find((item) => item.slug === slug) ?? null;
  if (staticResource) return applyResourcePresentation(staticResource);

  const db = bindings.DB;
  if (!db) {
    const sampleResource = sample[language].find((item) => item.slug === slug) ?? null;
    return sampleResource ? applyResourcePresentation(sampleResource) : null;
  }

  const resource = await db.prepare(`
    SELECT r.id, r.type, r.slug, r.status, r.youtube_url, r.content_date, r.series_slot, r.pdf_key,
      r.featured_image_key, r.author_email, u.display_name AS author_name, r.audience, r.published_at, r.updated_at,
      t.language, t.title, t.summary, t.body
    FROM resources r
    JOIN resource_translations t ON t.resource_id = r.id
    JOIN users u ON u.email = r.author_email COLLATE NOCASE
    WHERE r.status = 'published' AND r.slug = ? AND t.language = ?
    LIMIT 1
  `).bind(slug, language).first<ResourceSummary>();

  return resource ? applyResourcePresentation(resource) : null;
}

function filterResources(
  resources: ResourceSummary[],
  language: Language,
  options: { query?: string; type?: string; audience?: string; date?: string; limit?: number }
): ResourceSummary[] {
  const query = options.query?.toLocaleLowerCase(language) ?? "";
  const hiddenLegacyArticleSlugs = new Set(["what-is-the-gospel"]);
  return resources
    .filter((item) => !(item.type === "article" && hiddenLegacyArticleSlugs.has(item.slug)))
    .filter((item) => !options.type || item.type === options.type)
    .filter((item) => !options.audience || item.audience === options.audience)
    .filter((item) => sameCalendarDay(item.content_date, options.date))
    .filter((item) => !query || `${item.title} ${item.summary} ${item.body}`.toLocaleLowerCase(language).includes(query))
    .slice(0, options.limit ?? 24);
}

function mergeStaticResources(
  language: Language,
  options: { query?: string; type?: string; audience?: string; date?: string; limit?: number },
  dbResources: ResourceSummary[]
): ResourceSummary[] {
  const filteredStatic = filterResources(allStaticResources(language), language, { ...options, limit: 999 });
  const merged = [...filteredStatic, ...dbResources].sort((a, b) => {
    const dateA = a.content_date ?? a.published_at ?? a.updated_at ?? "";
    const dateB = b.content_date ?? b.published_at ?? b.updated_at ?? "";
    return dateB.localeCompare(dateA);
  });
  return merged.slice(0, options.limit ?? 24);
}

function uniqueResources(resources: ResourceSummary[]): ResourceSummary[] {
  const seen = new Set<string>();
  return resources.filter((resource) => {
    const titleKey = resource.type === "article"
      ? `${resource.type}:title:${normalizeResourceTitle(resource.title, resource.language)}`
      : "";
    const keys = [
      `${resource.type}:slug:${resource.slug}`,
      titleKey
    ].filter(Boolean);
    if (keys.some((key) => seen.has(key))) return false;
    keys.forEach((key) => seen.add(key));
    return true;
  });
}

function normalizeResourceTitle(title: string, language: Language): string {
  return title
    .toLocaleLowerCase(language)
    .replace(/[^\p{Letter}\p{Number}]+/gu, "");
}

function applyResourcePresentation(resource: ResourceSummary): ResourceSummary {
  if (resource.type !== "article") return resource;

  if (resource.slug === "five-ways-prosperity-gospel") {
    if (resource.language !== "en") return resource;

    return {
      ...resource,
      external_url: "https://www.desiringgod.org/interviews/five-ways-the-prosperity-gospel-makes-you-poor",
      external_label: "Read the original article"
    };
  }

  const isBookletEssaySummary = resource.id <= -300 && resource.id > -330;
  const preview = isBookletEssaySummary ? undefined : articlePreviewOverrides[resource.language]?.[resource.slug];
  const body = resource.slug === "article-mission-and-missionary"
    ? trimMissionOpeningVerse(resource.body ?? "", resource.language)
    : resource.body;

  return {
    ...resource,
    summary: preview ?? resource.summary,
    body
  };
}

function trimMissionOpeningVerse(body: string, language: Language): string {
  const marker = language === "th" ? "คำนำ" : language === "ko" ? "들어가는 말" : "Introduction";
  const index = body.indexOf(marker);
  return index > 0 ? body.slice(index).trim() : body;
}
